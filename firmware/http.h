/* HTTP: API секторов и раздача статики.
 *
 * Своими руками на сокетах BSD, а не esp_http_server: один цикл опроса
 * обслуживает и HTTP, и NBD (serve.c).
 *
 * API нарочно скудный — секторы и сведения о приводе. Всё остальное (список
 * «дискет», вход внутрь, работа с файлами) живёт на клиенте: там это менять
 * несравнимо легче, чем перепрошивать плату.
 *
 *   GET  /api/challenge             вызов для входа, JSON; БЕЗ подписи
 *   GET  /api/info                  сведения о приводе, JSON
 *   GET  /api/sectors/N?count=K     K секторов начиная с N, двоичным потоком
 *   GET  /api/scan?start=&stride=&count=&len=
 *                                   по len байт из каждого count-го сектора
 *                                   с шагом stride — обход меток «дискет»
 *   PUT  /api/sectors/N             записать тело, длина кратна 512
 *   POST /api/unlock                разрешить запись на время; 202
 *   POST /api/lock                  запретить сразу
 *   POST /api/flush                 сбросить кэш привода
 *   POST /api/reset                 аппаратный сброс привода; отвечает 202
 *                                   сразу, ход смотреть в поле drive у info
 *   GET  /...                       файл из каталога статики, / это index.html
 */
#ifndef COMBO_HTTP_H
#define COMBO_HTTP_H

#include "allow.h"
#include "netcfg.h"
#include "update.h"
#include "auth.h"

#include <stddef.h>
#include <stdint.h>

/* Предел на запрос. 64 сектора это 32 Кбайт — столько же, сколько у обхода
 * меток, и не случайно: ответ собирается в памяти целиком, а куча на ESP32 не
 * резиновая.
 *
 * ПОЧЕМУ НЕ 128. Сперва читаем всё, потом отвечаем — и сбой на середине
 * становится честным кодом с номером сектора в теле, а не обрывом соединения
 * после объявленной длины. Цена: вдвое больше запросов на ту же дискету, чем
 * при 128 (22 вместо 11), что при keep-alive недорого. */
#define HTTP_MAX_COUNT 64

/* Обход меток: дискеты лежат подряд с постоянным шагом, и клиенту нужен от
 * каждой только заголовок. Порознь это были бы сотни запросов по соединению на
 * каждый — на них и ушло бы всё время, диск тут ни при чём. Ответ собирается
 * целиком в памяти, чтобы об ошибке можно было доложить кодом, а не обрывом. */
#define HTTP_SCAN_BYTES 32768

/* Предел на тело запроса. Тело подписывается целиком, поэтому его приходится
 * прочитать и захешировать ДО того, как что-то делать: иначе подпись проверять
 * было бы уже поздно. Отсюда и потолок — столько же, сколько отдаём за раз. */
#define HTTP_MAX_BODY (HTTP_MAX_COUNT * 512)

typedef struct {
    uint16_t    port;
    int         read_only;
    uint32_t    sectors;        /* 0 — взять из опознания привода */
    const char *root;           /* каталог статики: "www" или "/spiffs" */
    const char *model;          /* из опознания при старте, а не на каждый запрос */
    const char *serial;
    /* Доступ к API: вызов-ответ с подписью, см. auth.h. Ноль или пустой секрет
     * внутри — проверки нет вовсе.
     *
     * Указатель, а не значение: таблица сессий должна пережить запрос, а
     * владеет ей вызывающий.
     *
     * СТАТИКА ТЕПЕРЬ ОТКРЫТА. Подписать обычную загрузку страницы браузер не
     * может — её тянет он сам, а не наш скрипт. Значит index.html и всё рядом
     * с ним доступны любому, кто дотянулся до порта. Секретов там нет, а API
     * под подписью; кому и этого много — ставит список адресов. */
    auth_t     *auth;
    /* Сколько секунд действует разрешение записи. 0 — разрешения не требуется
     * вовсе, пишем, пока не read_only.
     *
     * ЗАЧЕМ. Диск у машины один и ему тридцать лет, а самая вероятная беда с
     * ним — не злоумышленник, а случайная запись: чужая вкладка, ошибка в
     * морде, промах мышью. Окно превращает запись из состояния в намерение:
     * чтобы испортить диск, надо сперва явно сказать, что собираешься писать.
     *
     * Оно же ограничивает ущерб от захваченной сессии: подпись даёт доступ, но
     * не право писать, пока хозяин не разрешил. */
    uint32_t    write_window_s;
    /* Кого вообще пускать к порту. Ноль или пустой — всех. См. allow.h. */
    const allow_t *allow;
    /* Откуда взять силу сигнала для /api/info. Указатель, а не значение: ноль
       здесь — законный ответ «радио нет, не спрашивай». */
    int       (*rssi)(void);
    /* Обзор эфира для /api/wifi: пишет текст, возвращает длину или -1. Ноль —
       радио нет, и запрос честно ответит 501. */
    int       (*survey)(char *out, size_t max);
    /* Журнал платы для /api/log: тот же уговор, что и с обзором. */
    int       (*log)(char *out, size_t max);

    /* ---- обновление из сети ----
     *
     * Плата сама смотрит, что выпущено, но НЕ обновляется без спроса: ошибка в
     * сборке уехала бы разом на все платы, а откат ловит только незапуск.
     * Указатели, а не прямые вызовы: в режиме настройки обновления нет, и
     * там они ноль. */
    const update_state_t *(*update)(void);
    int       (*update_check)(void);
    int       (*update_apply)(void);

    /* ---- режим настройки: плата не в сети и ждёт, куда ей подключиться ----
     *
     * В нём морда показывает не диск, а выбор сети, и запросы настройки идут
     * БЕЗ ПОДПИСИ: секрета человек ещё не знает, а спросить его неоткуда. Это
     * безопасно ровно потому, что в этот миг плата не в сети — до неё можно
     * дотянуться только через её собственную точку, стоя рядом. */
    int         setup;
    /* Что видно в эфире: из этого списка человек выбирает свою сеть. */
    int       (*nets)(combo_net_t *out, int max);
    /* Запомнить сеть. Подключаться будет уже после перезагрузки — пробовать на
       ходу значило бы уронить ту самую точку, через которую с нами говорят. */
    int       (*join)(const char *ssid, const char *pass);
    /* Секрет платы — показать ОДИН РАЗ, пока сеть ещё ни разу не настраивали.
     * Иначе его негде взять: печатается он в UART, а шнурка нет. У настроенной
     * платы здесь ноль, и чужой, дотянувшийся до точки, секрета не увидит. */
    const char *setup_secret;
} http_cfg_t;

int  http_listen(uint16_t port);            /* слушающий сокет или -1 */

/* ОДИН запрос: 0 — соединение можно оставить (keep-alive), иначе закрыть.
 * По одному, чтобы общий цикл опроса обслуживал несколько соединений сразу и
 * долгий сеанс NBD не запирал морду. */
int  http_request(int fd, const http_cfg_t *cfg);

/* Всё соединение подряд — для случаев, где цикл не нужен. */


#endif
