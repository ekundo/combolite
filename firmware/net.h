/* Сервер NBD: диск «Вектора» как обычное блочное устройство по сети.
 *
 * ПОЧЕМУ NBD, А НЕ СВОЙ ПРОТОКОЛ. Цель — редактировать диск удалённо. Свой
 * протокол пришлось бы обслуживать своей же утилитой, а NBD монтируется
 * готовыми средствами:
 *
 *     nbd-client 192.168.1.50 10809 /dev/nbd0     # Linux
 *     mount /dev/nbd0 /mnt                        # и правь файлы как обычно
 *
 * Обмен у NBD простой: рукопожатие, дальше «прочитать со смещения» и
 * «записать по смещению». Сложные части (согласование, TLS, несколько
 * экспортов) не обязательны, и здесь их нет.
 */
#ifndef COMBO_NET_H
#define COMBO_NET_H

/* За ata_dev_t: net_resolve отдаёт опознанный привод наружу. */
#include "ata.h"

#include "allow.h"

#include <stdint.h>

typedef struct {
    uint16_t port;          /* 10809 — стандартный для NBD */
    int      read_only;     /* 1 — объявить экспорт только для чтения */
    uint32_t sectors;       /* 0 — взять из опознания привода */
    int      once;          /* 1 — обслужить одного клиента и вернуться */
    /* Пароля в протоколе NBD нет, поэтому секретом служит ИМЯ ЭКСПОРТА: клиент
     * обязан назвать его нашим токеном.
     *     nbd-client host 10809 /dev/nbd0 -N <токен>
     * Пусто или ноль — проверки нет. */
    const char *token;
    /* Кого пускать к порту NBD. Список СВОЙ, не общий с HTTP: за обратным
     * прокси к HTTP ходит только прокси, а NBD через него не ходит вовсе. */
    const allow_t *allow;
} net_cfg_t;

/* Слушает и обслуживает клиентов по одному. Возвращает 0, если отработал
 * единственного клиента при once, и отрицательное — если не встал на порт. */
int net_serve(const net_cfg_t *cfg);

/* То же по частям — чтобы один цикл опроса мог держать и NBD, и HTTP.
 * net_resolve заполняет sectors из опознания привода, если там ноль. Заодно
 * отдаёт наружу и сам ответ привода — модель с серийным номером нужны морде, а
 * второй раз опознавать привод ради них незачем. out можно не давать. */
int  net_resolve(net_cfg_t *cfg, ata_dev_t *out);
int  nbd_listen(uint16_t port);
void nbd_serve_conn(int fd, const net_cfg_t *cfg);   /* весь сеанс подряд */

/* По одному запросу — чтобы общий цикл опроса не запирался на всё время, пока
 * диск смонтирован. nbd_greet один раз после приёма, дальше nbd_request. */
int  nbd_greet(int fd, const net_cfg_t *cfg);
int  nbd_request(int fd, const net_cfg_t *cfg);

#endif
