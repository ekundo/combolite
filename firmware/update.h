/* Обновление из сети: проверить, что выпущено, и залить по нажатию.
 *
 * ЧТО ЗДЕСЬ ПРОИСХОДИТ. Плата раз в сутки читает манифест по известной ссылке,
 * сверяет версию со своей и запоминает ответ. Само обновление — только по
 * команде: раздача на парк устройств тем и опасна, что ошибка в сборке уезжает
 * на все платы разом, а откат ловит лишь незапуск. Прошивка, которая
 * запускается и работает неправильно, откатом не ловится вовсе.
 *
 * ЧЕМУ ПЛАТА ВЕРИТ. Двум разным вещам, и путать их не стоит. Сертификат
 * отвечает на вопрос «с кем я говорю» — его проверяет набор корневых из
 * ESP-IDF. Подпись отвечает на вопрос «что именно мне прислали» — её проверяет
 * вшитый открытый ключ (pubkey.h). Главная здесь вторая: сертификат ничего
 * не говорит о содержимом, а подпись не портится со временем.
 *
 * Пропускать проверку сертификата esp_http_client не умеет вовсе, а
 * устаревание набора корневых не страшно: протухни набор, перестанет работать
 * только самопроверка обновлений, плата продолжит работать, и обновить её
 * можно будет через combo.py. Кирпичом она не станет.
 *
 * Чего это не закрывает: тот, кто владеет и сертификатом, и раздачей, может
 * подсунуть СТАРУЮ, но честно подписанную прошивку. Для домашней платы это
 * приемлемо — тем более что откат на прежнюю версию у нас разрешён нарочно.
 */
#ifndef COMBO_UPDATE_H
#define COMBO_UPDATE_H

#include <stddef.h>

/* Что известно про обновление. Строки — для морды, поэтому по-английски. */
typedef struct {
    int  checked;               /* спрашивали ли хоть раз */
    int  available;             /* есть что ставить: app или fpga */
    int  app;                   /* версия прошивки в манифесте отличается от нашей */
    int  fpga;                  /* образ ПЛИС в манифесте не тот, что прошит */
    int  reboot;                /* после update_apply: нужна перезагрузка ESP */
    char version[48];           /* что предлагают, если спрашивали успешно */
    char error[120];            /* почему не вышло, если не вышло */
} update_state_t;

/* Начать поглядывать за манифестом. Первый раз — вскоре после старта, дальше
 * раз в сутки. Отдельной задачей: обращение к сети занимает секунды. */
void update_watch(void);

/* Что известно сейчас. Никогда не ноль. */
const update_state_t *update_now(void);

/* Спросить манифест немедленно. 0 — спросили (что узнали, см. update_now). */
int update_check(void);

/* Скачать и залить то, что обещано манифестом: образ ПЛИС -- в память и с
 * проверкой, потом морду и прошивку ESP, потом прошить ПЛИС. Прошивка ПЛИС
 * перезагружает «Вектор». Перезагрузку ESP делает вызывающий, если в
 * update_now()->reboot единица: ответ должен успеть дойти. */
int update_apply(void);

#endif
