/* Последовательности ATA. Переносимый C99: ни ESP-IDF, ни POSIX, только combo.h.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ — ограничения платы, а не недоделки:
 *
 * 1. Программного сброса (SRST) нет. Он живёт в регистре управления, а тот
 *    выбирается линией /CS1 — она на плате подтянута к единице и вывода ПЛИС
 *    не занимает (fpga/hdl/ide.v:67, как в оригинале). Значит нет и
 *    дублирующего регистра состояния: опрашивать приходится основной, седьмой.
 *
 * 2. Аппаратный сброс привода нам тоже недоступен. Его дёргает обращение
 *    процессора к порту 0x5F, причём с условием ~hold (fpga/hdl/ide.v:118) — то
 *    есть пока шину держим мы, даже «Вектор» привод не сбросит. Вывод: из
 *    зависшего состояния прошивка выйти не может, только доложить.
 *
 * 3. Опрос и никаких прерываний: линия INTRQ до ПЛИС не доведена.
 */
#ifndef COMBO_ATA_H
#define COMBO_ATA_H

#include <stdint.h>

#define ATA_SECTOR 512

enum {
    ATA_OK        =  0,
    ATA_E_LINK    = -1,     /* нет признака живости: оборван SPI или ПЛИС молчит */
    ATA_E_BUS     = -2,     /* арбитр не отдал шину */
    ATA_E_PREEMPT = -3,     /* владение отобрали посреди последовательности */
    ATA_E_TIMEOUT = -4,     /* привод не снял BSY */
    ATA_E_NODRQ   = -5,     /* привод не запросил передачу данных */
    ATA_E_DRIVE   = -6,     /* привод поднял ERR или DF */
    ATA_E_RANGE   = -7,     /* сектор за пределами диска */
    ATA_E_PROTO   = -8,     /* ПЛИС не ответила вовремя */
    ATA_E_CPU_BUSY = -9     /* «Вектор» работает с диском: писать нельзя */
};

typedef struct {
    char     model[41];
    char     serial[21];
    uint32_t sectors;       /* всего секторов, LBA28 */
    uint8_t  last_error;    /* содержимое регистра ошибки после сбоя */
} ata_dev_t;

const char *ata_strerror(int err);
uint8_t     ata_last_error(void);   /* регистр ошибки привода после ATA_E_DRIVE */
uint8_t     ata_last_status(void);  /* регистр состояния на последнем отказе опознания */

/* Объём последнего опознания. Нужен морде: сброс обнуляет его, переопознание
 * заполняет заново, а копия в настройке сервера снята один раз при старте и о
 * таких переменах не знает. */
uint32_t    ata_sectors(void);

/* Геометрия CHS последнего опознания: слова 1, 3 и 6 IDENTIFY -- цилиндров,
 * головок, секторов на дорожке. Нужна разметке карты из морды: эти числа
 * ложатся в заголовок диска (сектор 0, 80h..83h), и по ним МикроДОС
 * переводит свои адреса в CHS. Нули -- не опознан или привод их не дал. */
void        ata_chs(uint16_t *cyls, uint8_t *heads, uint8_t *spt);

/* Знает ли привод FLUSH CACHE. Ложь — не изъян: команда появилась в ATA-4, и
 * приводы старше просто пишут на носитель сразу. Нужна, чтобы сказать об этом
 * в журнале: иначе мгновенный «сброс кэша» выглядит подозрительно. */
int         ata_can_flush(void);

int ata_init(ata_dev_t *dev);
int ata_read (uint32_t lba, uint8_t *buf);        /* ровно 512 байт */
int ata_write(uint32_t lba, const uint8_t *buf);
int ata_flush(void);                              /* сбросить кэш привода */

/* ------------------------------------------------- чтение пачкой
 *
 * Подряд идущие секторы берутся ОДНОЙ командой привода: регистры пишутся раз,
 * дальше привод сам поднимает DRQ на каждый следующий сектор. Экономится не
 * время на шине привода — там те же 256 слов на сектор, — а обороты по SPI:
 * шесть записей регистров и ожидания BSY на каждый сектор превращались в
 * отдельные обращения к ПЛИС, и каждое стоит транзакции ESP.
 *
 * Длина пачки ограничена НЕ приводом (он берёт до 256 секторов), а арбитром:
 * окно владения 10 мс (GRANT_TICKS в fpga/hdl/ide_arb.v), а сектор обходится
 * примерно в 0,6 мс при SCK 8 МГц. Длину больше ATA_RUN звать можно: она
 * разбивается сама, и между кусками шина отпускается, чтобы «Вектор» не ждал
 * всю пачку.
 *
 * ПОЧЕМУ СЧИТАЕТСЯ ОТ ЧАСТОТЫ, А НЕ СТОИТ КОНСТАНТОЙ. На 8 МГц пачка из восьми
 * секторов занимает половину окна. На 4 МГц (умолчание, см. Kconfig) сектор
 * вдвое дороже, и восемь уже не укладываются — чтение каталогов сыплется с
 * «bus preempted mid-sequence at sector 5». Мегагерц на сектор — это и есть та
 * самая половина окна, поэтому длина пачки просто равна частоте в мегагерцах.
 */
#ifdef CONFIG_COMBO_SPI_HZ
#  define ATA_RUN_CALC (CONFIG_COMBO_SPI_HZ / 1000000)
#  if ATA_RUN_CALC < 1
#    define ATA_RUN 1
#  elif ATA_RUN_CALC > 8
#    define ATA_RUN 8
#  else
#    define ATA_RUN ATA_RUN_CALC
#  endif
#else
#  define ATA_RUN 8             /* без Kconfig частота SPI не задана */
#endif

/* done — сколько секторов успело прочитаться до отказа; можно передать нулём.
 * Без него отказ пачки не сказал бы, на каком секторе она споткнулась, а
 * сообщение «не читается сектор N» дороже, чем «не читается где-то в этих
 * восьми»: по нему сразу видно, испорчен диск или оборвалась связь. */
int ata_read_run(uint32_t lba, uint32_t count, uint8_t *buf, uint32_t *done);

/* ---------------------------------------------------------------- сброс
 *
 * Аппаратный сброс — единственный выход из зависшего состояния: программного у
 * нас нет, регистр управления выбирается линией /CS1, а она подтянута к
 * единице (см. оговорки выше).
 *
 * ЖДАТЬ ЗАВЕРШЕНИЯ НЕЛЬЗЯ. Привод, поднимающийся из остановленного состояния,
 * готов через секунды, а мёртвый не готов никогда — и всё это время
 * однопоточный цикл сервера не обслуживал бы никого. Поэтому сброс разложен на
 * начало и шаги: ata_reset_start() возвращается сразу, а ata_tick() двигает
 * дело по одному опросу за виток цикла.
 */
enum {
    ATA_DRIVE_UNKNOWN = 0,  /* ещё не трогали */
    ATA_DRIVE_RESET,        /* идёт сброс */
    ATA_DRIVE_READY,        /* готов */
    ATA_DRIVE_DEAD          /* не ожил за отведённый срок */
};

int ata_reset_start(void);          /* 0 — начат, иначе код ошибки */
int ata_drive_state(void);          /* одно из ATA_DRIVE_* */

/* Согласованность с «Вектором». Машина и мы пишем на один диск, и знать друг о
 * друге нам нечем: у неё каталог в ОЗУ. Отсюда два вопроса, на которые обязана
 * отвечать этот слой.
 *
 * touched липкий: он про «трогала ли с тех пор, как вы спрашивали», а не про
 * «трогает ли сейчас». Снимается ata_cpu_forget(). */
int  ata_cpu_touched(void);         /* «Вектор» трогал привод */
int  ata_cpu_quiet(void);           /* ...и сейчас молчит: писать можно */
void ata_cpu_forget(void);          /* снять липкий признак */
/* ДИАГНОСТИКА КВАЗИДИСКА, читается из ПЛИС. sel: 0 текущий регистр порта 0x10,
 * 1 липкое «какие разряды когда-либо выставлялись», 2 счётчик записей. */
uint8_t ata_kvaz_diag(uint8_t sel);
uint8_t ata_kvaz_diag2(uint8_t sel);
uint8_t ata_kvaz_diag3(uint8_t sel);
void    ata_kvaz_diag_clr(void);
void    ata_kvaz_latch(int on);
void    ata_kvaz_vid(int on);
void    ata_kvaz_vid_pol(int b);
void    ata_kvaz_cegate(int on);
void    ata_kvaz_ceby(int by_cas);

void ata_tick(void);                /* один шаг; звать из цикла обслуживания */

/* Блокирующая обёртка: начать и крутить шаги до конца. Для проверок и для
 * случаев, где замереть не жалко. Наружу через сеть НЕ выводить. */
int ata_reset(void);

/* Захват шины на несколько операций подряд: без него read/write берут и
 * отпускают её каждый раз, и арбитр честно возвращает шину «Вектору». */
int  ata_lock(void);
void ata_unlock(void);

/* Захват в ДОЛГОЕ владение — для записи, которую нельзя дать разорвать.
 * Вкладывается с ata_lock: внутренние захваты режима не меняют. */
int  ata_lock_long(void);

#endif
