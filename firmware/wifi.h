/* Подключение к сети. Отдельно от net.c: тому всё равно, откуда взялся адрес. */
#ifndef COMBO_WIFI_H
#define COMBO_WIFI_H

#include <stddef.h>
#include <stdint.h>

#include "netcfg.h"

/* Поднять станцию и подключиться. Возвращает 0 и кладёт адрес в ip
 * (четыре байта, как в сети), либо отрицательное при неудаче. */
int wifi_start(const char *ssid, const char *pass, uint32_t timeout_ms,
               uint8_t ip[4]);

/* Сила сигнала точки доступа в дБм: около -40 — точка рядом, -70 уже далеко,
 * -85 на грани. Ноль, если станция не подключена.
 *
 * ЗАЧЕМ ЭТО НАРУЖУ. Скорость морды на плате зависит от канала сильнее, чем от
 * кода: один и тот же обход каталогов занимает то 5, то 15 секунд, смотря к
 * какой точке прицепилась плата. Пока сила сигнала не видна, любые замеры на
 * плате сравнивать нельзя. */
int wifi_rssi(void);

/* Напечатать, что плата видит в эфире под своим именем сети, и к чему
 * подключена сейчас. Нужна, когда «сигнал слабый» звучит неправдоподобно:
 * точек с одним именем бывает несколько, и глазами их не различить. */
void wifi_survey(void);

/* То же самое текстом, для морды. Возвращает длину записанного или -1.
 *
 * Текст, а не разобранные поля: это ответ ЧЕЛОВЕКУ, и читать его будут глазами.
 * Заводить ради него структуру, разбор и вёрстку значило бы трижды переложить
 * одно и то же, чтобы получить те же четыре строки. */
int wifi_survey_text(char *out, size_t max);

/* ------------------------------------------------------------ настройка
 *
 * Плата, которая не смогла подключиться, поднимает СВОЮ точку доступа и ждёт,
 * когда ей скажут, куда подключаться. Без этого первая же смена пароля на
 * роутере превращала бы её в молчащую коробку. */

/* Поднять свою точку. Имя кладётся в name — его человек ищет в списке сетей на
 * телефоне. Возвращает 0 или отрицательное. */
int wifi_setup_start(char *name, size_t max);

/* Мы сейчас в режиме настройки? */
int wifi_setup_active(void);

/* Что видно в эфире — ВСЕ сети, а не только своя: из этого списка человек и
 * выбирает. Возвращает сколько нашлось или -1. */
int wifi_networks(combo_net_t *out, int max);

#endif
