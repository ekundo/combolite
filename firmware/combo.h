/* Наша ПЛИС: команды ide_remote.v и разбор состояния.
 *
 * Слой ровно между транспортом и ATA. Ничего не знает про приводы — только
 * «прочитать регистр», «перегнать 256 слов», «взять шину».
 */
#ifndef COMBO_H
#define COMBO_H

#include <stdint.h>

/* команды (см. заголовок fpga/hdl/ide_remote.v) */
#define C_STATUS  0x00
#define C_REG_RD  0x10          /* | номер регистра */
#define C_RES     0x18
#define C_REG_WR  0x20          /* | номер регистра */
#define C_REQ     0x30
#define C_REL     0x31
#define C_RESET   0x32          /* сброс привода; действует только при захвате */
#define C_REQ_LONG 0x33         /* взять шину в долгое владение */
#define C_SEEN_CLR 0x34         /* снять липкий признак «процессор трогал» */
#define C_DIAG_CLR 0x35         /* обнулить счётчики наблюдателя за шиной */
#define C_LATCH_ON 0x36         /* заморозить защёлку адреса на время обращения */
#define C_LATCH_OFF 0x37        /* вернуть прежнее поведение */
#define C_VID_ON 0x1D           /* гасить такт защёлки на видеоспаде ~RAS */
#define C_VID_OFF 0x1E          /* вернуть прежнее поведение */
#define C_VID_POLA 0x1F         /* строб принадлежит ПРЕДЫДУЩЕМУ спаду ~RAS */
/* 0x30 БРАТЬ НЕЛЬЗЯ: там C_REQ, и в case ПЛИС выиграла бы его ветка.
   Команда вернула бы состояние и выглядела исполненной, а vid_pol не
   поменялся бы. Карта занятых кодов — в шапке fpga/hdl/ide_remote.v. */
#define C_VID_POLB 0x46         /* строб принадлежит ЭТОМУ спаду */
#define C_VI53_ON  0x47         /* эмуляция ВИ53 в звук (по сбросу) */
#define C_VI53_OFF 0x48         /* выключить: звук таймера даёт сама машина (провод на 42) */
#define C_MOUSE    0x42         /* отчёт мыши: + кнопки (0 лев, 1 прав, 2 сред), dx, dy, колесо -- как у USB HID */
#define C_MOUSE_OFF 0x43        /* мыши нет: порт D4h не отвечает */
#define C_DEV      0x49         /* + маска выключенных: 0 ВГ93, 1 КД 0x10, 2 КД 0x11, 3 IDE, 4 AY, 5 зеркало */
#define C_FDC_RDY  0x4A         /* + откуда готовность ВГ93: 0 контакт 34, 1 по индексу, 2 всегда */
#define C_KEYS     0x4B         /* + клавиши: 0 отпустить, 1 ВВОД 50 мс, 2 СБР 50 мс, 3 держать ВВОД ещё 2 с */
#define C_LOADER   0x4C         /* + подставной загрузчик: 0 выключить, 1 взвести, 2 взвести и нажать СБР */
#define C_VGA      0x4E         /* + режим VGA: разряд 0 -- 800x600@60, иначе 50 Гц с привязкой к машине */
#define C_FDC_PC   0x4F         /* + предкомпенсация ВГ93: 3..0 шаги по 62,5 нс (0 нет), 4 -- только с 44-й дорожки */
#define C_BOOT     0x56         /* + разряд 0: после ВВОД с клавиатуры -- подставной загрузчик (fpga/hdl/rom_sense.v);
                                   разряд 1: автозапуск загруженного, BOOT26 и ПЗУ (fpga/hdl/fakerom.v) */
#define C_SCRROW   0x52         /* + строка картинки y: заявка на строку экрана (scr_buf.v) */
#define C_SCRRD    0x53         /* дальше 131 байт: A5h/00 готово, y, прокрутка, 128 байт (слой 0..3 x колонка 0..31) */
#define C_PALRD    0x57         /* дальше 17 байт: палитра машины, ячейки 0..15, BBGGGRRR, и порт B {0,0,0,512,бордюр} (fpga/hdl/vid_rec.v) */
#define C_CHRD     0x58         /* канал «Вектор» -> ESP: дальше {0, flushed, пусто к «Вектору», 10101}, пары (признак, байт) (fpga/hdl/vchan.v) */
#define C_CHWR     0x59         /* канал ESP -> «Вектор»: дальше байты до подъёма CS */
#define CHAN_DEPTH 14           /* очередь канала, байт (fpga/hdl/vchan.v) */
#define C_DIAG4    0x60         /* 0x60..0x67: новые узлы, раскладка -- в конце fpga/hdl/top.v */
#define C_DIAG5    0x68         /* 0x68..0x6F: растр, дисковод, набор узлов битстрима (0x6F) */
#define C_DIAG6    0x70         /* 0x70..0x77: сброс с клавиатуры (fpga/hdl/rom_sense.v) */
#define C_DIAG7    0x78         /* 0x78..0x7F: ВГ93 -- команда, состояние, дорожка, сектор, счётчики (fpga/hdl/fdc.v, dbg) */
#define C_DIRTY    0x4D         /* карта блоков зеркала: дальше 32 байта, разряд i байта j -- блок 8j+i по 256 байт; чтение гасит */

/* ЧТЕНИЕ С ЯВНЫМ НОМЕРОМ БУФЕРА, младший разряд кода — номер. Нужны потому,
   что "буфер, которым владеет ESP" меняется по КОНЦУ переноса, то есть
   асинхронно потоку команд: опоздавшая выборка взяла бы следующий сектор
   вместо прежнего. Разбор — fpga/hdl/ide_remote.v. */
#define C_BUF_RD_N 0x44         /* | номер: выборка буфера N по SPI */
#define C_SEC_RD_N 0x54         /* | номер: привод -> буфер N */
#define C_CE_ON    0x19         /* выбирать кристалл ОЗУ только на стробах */
#define C_CE_OFF   0x1A         /* вернуть прежнее поведение */
#define C_CE_CAS   0x1B         /* квалифицировать выбор по ~CAS */
#define C_CE_STB   0x1C         /* квалифицировать по стробам процессора */
#define C_DIAG     0x38         /* 0x38..0x3F: восемь байт диагностики квазидиска */
#define C_DIAG2    0x28         /* 0x28..0x2F: измерения наблюдателя за шиной */
#define C_DIAG3    0x08         /* 0x08..0x0F: фаза строба относительно циклов шины */
#define C_BUF_RD  0x40
#define C_BUF_WR  0x41
#define C_SEC_RD  0x50
#define C_SEC_WR  0x51

/* состояние — первый байт любого ответа */
#define ST_GRANT    0x01        /* шина захвачена */
#define ST_CYC      0x02        /* идёт цикл обращения к приводу */
#define ST_BLK      0x04        /* идёт перенос блока */
#define ST_TIMEOUT  0x08        /* владение отбиралось по времени, липкий */
#define ST_LONG     0x10        /* запрошено долгое владение */
#define ST_QUIET    0x20        /* процессор молчит дольше порога: писать можно */
#define ST_CPU_SEEN 0x40        /* процессор трогал привод, липкий до C_SEEN_CLR */
#define ST_ALIVE    0x80        /* всегда 1: отличить от оборванной линии */

#define COMBO_SECTOR 512

uint8_t combo_status(void);

/* ДИАГНОСТИКА КВАЗИДИСКА. Регистр порта 0x10 — страницы, стековый режим и окна
 * Баркаря — на плате только для записи, и что туда пишет MicroDOS, иначе не
 * узнать никак. Три байта:
 *   sel = 0  текущее значение регистра;
 *   sel = 1  ЛИПКОЕ «какие разряды когда-либо выставлялись» — одиночную запись
 *            мусора иначе не поймать вовсе;
 *   sel = 2  счётчик записей в порт, с насыщением на 255.
 * Шину привода не занимает: это чтение регистра внутри ПЛИС. */
uint8_t combo_diag(uint8_t sel);
uint8_t combo_diag2(uint8_t sel);
uint8_t combo_diag3(uint8_t sel);
/* Блоки 4 и 5 (0x60..0x6F): новые узлы, растр, дисковод, набор узлов
 * битстрима. Раскладка -- в конце fpga/hdl/top.v, разбор -- в board.c. */
uint8_t combo_diag4(uint8_t sel);
uint8_t combo_diag5(uint8_t sel);
/* Блок 6 (0x70..0x77): сброс с клавиатуры, раскладка -- в конце
 * fpga/hdl/rom_sense.v. Есть, только если в 0x6E стоит BF2_KBD (board.h). */
uint8_t combo_diag6(uint8_t sel);
uint8_t combo_diag7(uint8_t sel);
/* Палитра машины, 16 байт BBGGGRRR, и 17-й -- порт B (C_PALRD). Есть, если в
 * блоке 5, байт 2, стоит разряд 6 (board.h, board_palette). */
void    combo_pal_read(uint8_t pal[17]);
/* То же чтение 0x57, но до конца: 2048 байт -- палитра, порт B, номер
 * следующей записи журнала портов (17), счёт кадров (18) и сам журнал с 1024
 * (fpga/hdl/vid_rec.v). Пока идёт чтение, журнал стоит. */
void    combo_pal_log(uint8_t buf[2048]);
void    combo_diag_clr(void);
void    combo_latch(int on);
void    combo_vid(int on);
void    combo_vid_pol(int b);
void    combo_cegate(int on);
void    combo_ceby(int by_cas);
int     combo_alive(void);

int     combo_request(void);            /* взять шину, ждать ST_GRANT */

/* То же, но в ДОЛГОЕ владение: арбитр не отберёт шину через свои 10 мс, а
 * продержит до предела в 2,55 с. Нужно там, где запись нельзя дать разорвать
 * посередине. Зависшую сторону страхует сторож в ПЛИС: он снимает запрос сам,
 * если по SPI больше секунды ничего не приходило. */
int     combo_request_long(void);
void    combo_release(void);

/* Дёрнуть RESET привода. ПЛИС держит линию 50 мкс сама и исполнит команду
 * только при захваченной шине — иначе привод перезапустится посреди
 * последовательности процессора. Готовности НЕ ждёт, это дело ata.c. */
void    combo_reset_drive(void);

int     combo_reg_write(uint8_t reg, uint16_t value);
int     combo_reg_read(uint8_t reg, uint16_t *out);

/* Буфер отдаёт и принимает слова СТАРШИМ БАЙТОМ ВПЕРЁД — так устроен
 * ide_remote.v. Перестановкой в привычный порядок занимается ata.c. */
void    combo_buf_read(uint8_t *dst);         /* 512 байт */
void    combo_buf_read_n(int buf, uint8_t *dst);   /* то же, буфер назван явно */
void    combo_buf_write(const uint8_t *src);

int     combo_sector_from_drive(void);        /* привод -> буфер, с ожиданием */
int     combo_sector_to_drive(void);          /* буфер -> привод, с ожиданием */

/* Снять липкий признак «процессор трогал привод».
 *
 * Порядок такой: снять — прочитать — посмотреть снова. Если после чтения
 * признак опять поднят, «Вектор» лазил на диск ПОКА мы читали, и прочитанному
 * верить нельзя: у машины каталог в ОЗУ, и она могла переписать то, что мы
 * только что взяли. */
void    combo_seen_clear(void);
int     combo_cpu_touched(void);              /* признак поднят? */

/* То же, но врозь: пустить перенос и дождаться его отдельно. Между этими двумя
 * вызовами ESP свободна и тянет по SPI ПРЕДЫДУЩИЙ сектор — буферов в ПЛИС два,
 * и она сама следит, чтобы стороны не сошлись на одном. Ради этого перекрытия
 * сектор и обходится не в сумму 190 + 510 мкс, а в большее из двух. */
void    combo_block_start(int write);
void    combo_block_start_n(int buf);              /* чтение в буфер N */
int     combo_block_wait(void);

int     combo_wait(uint8_t mask, int want, uint32_t timeout_us, uint8_t *last);

/* Команда без ответа: один байт или байт с аргументом в той же выборке
 * (C_DEV, C_FDC_RDY, C_KEYS, C_LOADER, C_VGA, C_FDC_PC, C_BOOT, C_SCRROW). Что они
 * значат -- в combo.h выше и в board.c. */
void    combo_cmd(uint8_t cmd);
void    combo_cmd_arg(uint8_t cmd, uint8_t arg);

/* Отчёт мыши, пакет C_MOUSE целиком в одной выборке: оборванный ПЛИС
 * выбрасывает. Числа -- как в отчёте USB HID, со знаком. */
void    combo_mouse(uint8_t buttons, int8_t dx, int8_t dy, int8_t wheel);

/* Карта блоков зеркала, 32 байта. Чтение гасит: блок, записанный машиной
 * после чтения, придёт в следующий раз. */
void    combo_dirty(uint8_t map[32]);

/* Строка экрана: заявка C_SCRROW + y, потом C_SCRRD до готовности.
 * out -- 131 байт: [0] A5h готово / 00 ещё нет, [1] y, [2] прокрутка,
 * [3..130] слои 0..3 по 32 колонки (scr_buf.v). */
void    combo_scr_read(uint8_t out[131]);
/* Только первые два байта ответа: готова ли строка и какая. Опрос готовности
 * дешевле на 129 байт; недочитанный ответ ПЛИС не портит -- признак
 * готовности живёт до следующей заявки. */
void    combo_scr_peek(uint8_t *ready, uint8_t *row);

/* Канал «Вектор» <-> ESP (fpga/hdl/vchan.v, порты 28h-2Dh как у UART 16550). Чтение забирает не
 * больше max байт: ПЛИС перед каждым даёт признак «есть ещё». *free --
 * сколько можно положить к «Вектору»: CHAN_DEPTH, если очередь пуста, иначе 0
 * (счёта места в ПЛИС нет, он стоил бы цепочек переноса); *flushed --
 * «Вектор» очистил канал с прошлого опроса. -1 -- канала нет: старый
 * битстрим отвечает на 0x58 состоянием, у которого разряд 7 всегда единица,
 * а здесь первый байт -- {0, flushed, пусто, 10101}. Иначе -- сколько взято. */
/* Счетчики канала для журнала ESP (vchan_esp.c): опросы, отказы, байты туда и
 * обратно, очистки и последний байт состояния от ПЛИС. */
typedef struct { uint32_t polls, bad, in, out, flushes; uint8_t first; } combo_chan_stat_t;
extern combo_chan_stat_t combo_chan_stat;
int     combo_chan_read(uint8_t *buf, int max, int *free, int *flushed);
/* Положить n байт в очередь к «Вектору». Места ПЛИС не проверяет за нас:
 * лишнее пропадает, поэтому n -- не больше *free из последнего чтения. */
void    combo_chan_write(const uint8_t *buf, int n);

#endif
