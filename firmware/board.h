/* Всё, что ПЛИС делает для машины помимо привода: выключатели устройств, ВГ93,
 * VGA, ВИ53, клавиши ВВОД и СБР, подставной загрузчик, диагностика новых узлов.
 *
 * ЗАЧЕМ ОТДЕЛЬНО ОТ ata.c. Там привод и шина IDE; здесь настройки и узлы,
 * которые от привода не зависят и есть не в каждом битстриме. Какие есть,
 * ПЛИС говорит сама: байт 0x6F -- набор узлов, 0x6E -- версия раскладки
 * (конец fpga/hdl/top.v). Старый битстрим на эти коды отвечает состоянием, и
 * board_probe это отличает.
 *
 * НАСТРОЙКИ ЖИВУТ В ПЛИС ДО ПЕРВОГО СБРОСА ПО ПИТАНИЮ. Включение и перезаливка
 * возвращают их к умолчаниям (fpga/hdl/ide_remote.v, блок por), поэтому прошивка
 * хранит их у себя и заливает обратно: при старте, когда ПЛИС ожила после
 * молчания, и после сеанса XVC. */
#ifndef COMBO_BOARD_H
#define COMBO_BOARD_H

#include <stdint.h>

/* Набор узлов битстрима, байт 0x6F. */
#define BF_FDC    0x01
#define BF_VI53   0x02
#define BF_MOUSE  0x04
#define BF_KEYS   0x08
#define BF_LOADER 0x10
#define BF_MIRROR 0x20
#define BF_WATCH  0x40
#define BF_VIDEO  0x80
/* Байт 0x6E, младшие разряды. */
#define BF2_AY          0x01
#define BF2_KVAZ2       0x02
#define BF2_AUDIO_SPLIT 0x04
#define BF2_KBD         0x08    /* сброс с клавиатуры различается, есть C_BOOT и блок 6 */

/* Разряды маски выключенных устройств, C_DEV. */
#define DEV_FDC    0x01
#define DEV_KVAZ1  0x02
#define DEV_KVAZ2  0x04
#define DEV_IDE    0x08
#define DEV_AY     0x10
#define DEV_MIRROR 0x20
#define DEV_MASK   0x3F

typedef struct {
    uint8_t dev_off;    /* DEV_*: 1 -- устройство не отвечает на шине */
    uint8_t fdc_rdy;    /* готовность ВГ93: 0 контакт 34, 1 по индексу, 2 всегда */
    uint8_t fdc_pc;     /* предкомпенсация: 3..0 шаги по 62,5 нс, 4 -- с 44-й дорожки */
    uint8_t vga60;      /* 1 -- VGA 800x600@60 (по умолчанию), 0 -- 50 Гц с привязкой к машине */
    uint8_t vi53_off;   /* 1 -- эмуляция ВИ53 выключена, звук даёт сама машина */
    uint8_t boot;       /* BOOT_*: чем грузится машина */
    uint8_t fdd_cable;  /* шлейф дисковода: 0 Шугарт (A: 10, B: 12, мотор 16),
                           1 ПК с перекруткой (A: 12, B: 16, мотор 10), fpga/hdl/top.v */
} board_settings_t;

/* Чем грузится машина. Настройка живёт в прошивке: при включении ESP сама
 * решает, отпустить ли ВВОД (загрузка из ПЗУ) или нажать СБР с подставным
 * загрузчиком. В ПЛИС уходит только последнее (C_BOOT). */
#define BOOT_ROM    0       /* как без платы: загрузчик из ПЗУ */
#define BOOT_POWER  1       /* при включении -- подставной загрузчик */
#define BOOT_VVOD   2       /* и после каждого ВВОД с клавиатуры тоже */

/* Как в ПЛИС по сбросу. Тогда плата без сохранённых настроек ведёт себя ровно
 * так же, как сама ПЛИС. VGA по умолчанию -- 60 Гц (VESA 800x600): его берет
 * любой монитор, а 576p при 50 Гц -- не всякий. Сохранённая запись
 * любой версии несёт vga60 сама, выбор хозяина при обновлении не трогается. */
#define BOARD_SETTINGS_DEFAULT { 0, 1, 0, 1, 0, BOOT_ROM, 0 }

int  board_settings_valid(const board_settings_t *s);

/* Прочитать набор узлов. 0 -- битстрим знает блоки 4 и 5, иначе -1 (старый
 * битстрим, ПЛИС не загружена, обрыв SPI). */
int     board_probe(void);
int     board_present(void);        /* последний board_probe удался */
uint8_t board_features(void);       /* BF_*, ноль без board_present */
uint8_t board_features2(void);      /* BF2_* */

/* Загрузить сохранённое, опознать ПЛИС и залить настройки. Звать один раз,
 * после link_open. */
void board_init(void);

/* Текущие настройки (то, что прошивка считает залитым). */
void board_get(board_settings_t *out);

/* Залить в ПЛИС и сохранить. -1 -- значения вне диапазона, ничего не
 * менялось. */
int  board_set(const board_settings_t *s);

/* Залить ещё раз то, что есть, -- после перезаливки ПЛИС. */
void board_reapply(void);

/* Сохранение: NVS на плате, без ESP-IDF -- память. */
int  board_settings_load(board_settings_t *out);   /* 0 -- было сохранено */
int  board_settings_save(const board_settings_t *s);

/* Клавиши машины. -1 -- в битстриме нет автозапуска. */
#define KEY_RELEASE 0       /* отпустить всё сейчас же */
#define KEY_VVOD    1       /* ВВОД на 50 мс: перезагрузка из ПЗУ */
#define KEY_SBR     2       /* СБР на 50 мс: загрузка с отключённым ПЗУ */
int  board_keys(int what);

/* Нажат ли ВВОД прямо сейчас. С включения ПЛИС держит его 2 с сама. */
int  board_vvod_held(void);

/* Продлить удержание ВВОДа ещё на 2 с -- ТОЛЬКО если он уже нажат. Команда 3
 * на отпущенной клавише сама нажала бы ВВОД и перезагрузила работающую
 * машину (fpga/hdl/autostart.v), поэтому проверка здесь, а не у вызывающего.
 * 1 -- продлено, 0 -- не нажат, -1 -- автозапуска нет. */
int  board_vvod_extend(void);

/* Подставной загрузчик. -1 -- в битстриме его нет. */
#define LOADER_OFF  0
#define LOADER_ARM  1       /* взвести: окно откроется по нашему СБР */
#define LOADER_BOOT 2       /* взвести и нажать СБР */
int  board_loader(int what);

/* Отпустить машину, которую ПЛИС держит ВВОДОМ с включения: при BOOT_ROM --
 * отпустить ВВОД, и машина грузится из ПЗУ; иначе -- взвести загрузчик и
 * нажать СБР (ВВОД autostart.v отпустит сам, через паузу между клавишами).
 * Нет загрузчика в битстриме -- тоже из ПЗУ. 1 -- нажат СБР, 0 -- отпущен
 * ВВОД, -1 -- клавиш нет. */
int  board_release(void);

/* Снимок экрана машины: 256 строк картинки по 128 байт -- слой 0 (8000h)
 * колонки 0..31, слой 1, 2, 3; в байте левая точка -- старший разряд. Строка y
 * -- уже с прокруткой, как на экране. Цвета -- отдельно, board_palette. 0 --
 * снято, -1 -- нет генератора кадра, -2 -- строка не пришла (выборка стоит).
 * Занимает шину SPI на ~150 мс. */
#define SCR_ROWS      256
#define SCR_ROW_BYTES 128
int  board_screen(uint8_t *frame);

/* Палитра машины: 16 байт BBGGGRRR, ячейка -- номер цвета точки; 17-й байт --
 * порт B: разряд 4 -- режим 512 точек, 3..0 -- бордюр. Это палитра и режим,
 * какими их ведёт ПЛИС по записям в порты вне картинки; смены под лучом
 * (мультиколор) на снимок не попадают. 0 -- прочитана, -1 -- битстрим её не
 * отдаёт. */
#define SCR_PAL_BYTES 17
#define SCR_PB_512    0x10
int  board_palette(uint8_t pal[SCR_PAL_BYTES]);

/* Журнал записей машины в порты палитры и порта B -- диагностика, разбор в
 * fpga/hdl/vid_rec.v («журнал записей»): 2048 байт как их отдаёт ПЛИС. 0 --
 * прочитан, -1 -- битстрим палитру не отдаёт. Старый битстрим журнала не
 * ведёт: за 17-м байтом там по кругу повторяется палитра. */
#define PAL_LOG_BYTES 2048
int  board_pal_log(uint8_t buf[PAL_LOG_BYTES]);

/* Блоки диагностики 4 и 5 как есть, по восемь байт. */
void board_diag(uint8_t d4[8], uint8_t d5[8]);
/* Блок 6; без BF2_KBD -- нули. */
void board_diag6(uint8_t d6[8]);

/* Разобранная диагностика и настройки -- JSON для /api/board. Возвращает
 * длину, как snprintf. */
int  board_json(char *out, int max);

/* Шаг фоновых дел: замечает, что ПЛИС ожила после молчания (перезаливка), и
 * заливает настройки. Звать из цикла обслуживания, дёшево. */
void board_tick(void);

/* Попросить залить настройки на ближайшем шаге: после сеанса XVC. Можно
 * звать из другой задачи. */
void board_reapply_later(void);

#endif
