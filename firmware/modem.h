/* Wi-Fi модем: AT-команды и telnet, как Zimodem и WiFi232 у старых машин.
 *
 * ТОЛЬКО МОДЕМ. ESP держит соединение и понимает AT-команды; всё прочее --
 * экран, ANSI, кодировки, история, XMODEM, IRC -- дело программ на «Векторе».
 * Так модем повторяется где угодно: в эмуляторе это два порта (doc/MODEM.md)
 * и этот же файл.
 *
 * ПОТОК. Со стороны машины модем -- две трубы байтов:
 *   modem_put  -- байт от машины: в командном режиме -- в строку команды, в
 *                 соединении -- в сеть (у telnet 0xFF удваивается);
 *   modem_get  -- байт к машине: ответы модема и данные из сети (команды
 *                 telnet вырезаны).
 * Трубы -- кольца с одним писателем и одним читателем: modem_put и modem_get
 * можно звать из одной задачи, modem_poll -- из другой, без замка.
 * Сеть обслуживает modem_poll: неблокирующие сокеты, по шагу за вызов. Имя
 * хоста разрешается блокирующим getaddrinfo, поэтому на плате модем живёт в
 * своей задаче (modem_esp.c), а не в опросе канала.
 *
 * КОМАНДЫ (заглавные или строчные, AT в начале строки, CR в конце):
 *   AT              OK
 *   ATZ             сброс: эхо вкл, повесить трубку
 *   ATE0 / ATE1     эхо команд выкл / вкл
 *   ATI             имя модема
 *   ATDT host:port  набрать (ATD и ATDP так же; порт по умолчанию 23)
 *   ATH / ATH0      повесить трубку
 *   ATO             вернуться в соединение после +++
 *   ATDL            набрать прошлый адрес ещё раз
 *   ATBBS [слово]   список BBS из Telnet BBS Guide (bbslist.h): без слова --
 *                   сколько их, со словом -- поиск, до 15 строк с номерами
 *   ATDS n          набрать BBS номер n из списка
 *   A/              повторить прошлую команду (без CR)
 *   AT?             справка
 * ЗБ (08h или 7Fh) стирает знак строки. ESC-последовательности -- мимо.
 * Ответы словами: OK, ERROR, CONNECT, NO CARRIER, NO ANSWER.
 * В соединении +++ с тишиной не меньше секунды до и после -- в командный
 * режим, соединение остаётся.
 *
 * TELNET (RFC 854 и соседи). Вид соединения -- по первому байту сервера: IAC
 * -- telnet, текст или молчание секунду -- сырой TCP (IRC и прочее), байты
 * как есть. У telnet соглашаемся на ECHO и SUPPRESS-GO-AHEAD от сервера,
 * сами готовы к SGA, TERMINAL-TYPE (отвечаем "ANSI") и NAWS (80x25); BINARY
 * просим сразу в обе стороны -- файлы идут через модем как есть, CR без NUL.
 * Остальное вежливо отклоняем. Пока вид не ясен, байты от машины ждут.
 *
 * GOPHER ПОВЕРХ HTTPS. ATDT хост.github.io:70 соединяет с мостом, а не с
 * сетью: строка выбора -> https://хост/путь (fetch.h), тело -- как ответ
 * Gopher, конец -- NO CARRIER (подробности -- modem.c, doc/MODEM.md). */
#ifndef COMBO_MODEM_H
#define COMBO_MODEM_H

#include <stdint.h>

#define MODEM_COLS      80
#define MODEM_ROWS      24              /* NAWS: как VT100; 25-я строка у TERM -- состояние */

#define MODEM_NAME      "ComboLite Wi-Fi modem"

void modem_init(void);
void modem_put(uint8_t b);
int  modem_get(uint8_t *b);             /* 1 -- байт есть */
int  modem_online(void);                /* соединение есть, и мы в нём */
int  modem_line(void);                  /* соединение есть (может, мы в командах после +++) */
/* Шаг сети и таймеров. now_ms -- монотонные миллисекунды. */
void modem_poll(uint32_t now_ms);

/* Плата: modem_init и задача модема (modem_esp.c). */
void modem_start(void);

#endif
