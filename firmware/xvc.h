/* Xilinx Virtual Cable: JTAG по TCP для openFPGALoader с компьютера.
 *
 * ЗАЧЕМ ЧУЖОЙ ПРОТОКОЛ, А НЕ СВОЯ ЗАЛИВКА. Записать флеш MachXO2 — это порядок
 * команд, ожиданий и опросов занятости, и ошибка в нём оставляет кристалл
 * пустым. openFPGALoader этот порядок уже знает; ему не хватает только кабеля.
 * XVC и есть кабель: три команды, и ни одной про Lattice. Плата сдвигает биты,
 * всё остальное делает компьютер.
 *
 * Протокол (Xilinx XAPP1251; в openFPGALoader — кабель `xvc-client`):
 *   "getinfo:"                      -> "xvcServer_v1.0:<байт на вектор>\n"
 *   "settck:" <u32 период, нс>      -> те же 4 байта (частоту не меняем)
 *   "shift:"  <u32 бит> <TMS> <TDI> -> TDO
 * Числа младшим байтом вперёд, внутри байта младший бит идёт первым.
 *
 * Файл переносим: ни ESP-IDF, ни ног — только сокет и `jtag_io`.
 */
#ifndef COMBO_XVC_H
#define COMBO_XVC_H

#include "jtag.h"

#define XVC_PORT    2542
#define XVC_MAX     2048        /* байт на вектор TMS (и столько же на TDI) */

/* Обслужить одно соединение до его закрытия или первой ошибки.
 * Возврат: 0 — клиент закрыл сам, -1 — ошибка или мусор в протоколе.
 * Сколько сдвигов прошло — в *shifts, если не NULL. */
int xvc_session(int fd, const jtag_io *io, long *shifts);

/* Открыть на плате приём XVC на `secs` секунд, только для адреса `peer`
 * (порядок сети, как в sockaddr_in). Пока соединение живо, ноги JTAG заняты;
 * по закрытию и по истечении срока — отпущены. Повторный вызов продлевает срок.
 * Без проводов JTAG — JTAG_ENOHW (jtag_fake.c). */
int jtag_xvc_open(uint32_t peer, int secs);

#endif
