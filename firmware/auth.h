/* Доступ к API: вызов-ответ с подписью каждого запроса.
 *
 * ЗАЧЕМ НЕ ТОКЕН. У нас нет TLS, а без него любая схема с ПОВТОРНО
 * ИСПОЛЬЗУЕМЫМ секретом — токен, Basic, кука сессии — сводится к одному:
 * перехватил раз, владеешь всегда. Здесь по проводу не идёт ни секрет, ни
 * что-либо, что можно послать второй раз.
 *
 * КАК УСТРОЕНО:
 *
 *   1. GET /api/challenge -> nonce = t ‖ HMAC(M, t), где M случаен и создаётся
 *      при запуске. Плата НИЧЕГО НЕ ЗАПОМИНАЕТ: вернувшийся nonce она проверит,
 *      пересчитав подпись. Поэтому дёргать вызов сколько угодно бесполезно —
 *      выделять нечего, а это ровно та ошибка, из-за которой в TCP появились
 *      SYN-cookies.
 *
 *   2. K = HMAC(секрет, nonce) — считают обе стороны, по проводу K не идёт.
 *
 *   3. Каждый запрос несёт nonce, номер и подпись:
 *
 *        подпись = HMAC(K, nonce ‖ '\n' ‖ номер ‖ '\n' ‖ метод ‖ '\n'
 *                          ‖ путь с запросом ‖ '\n' ‖ hex(combo_sha256(тело)))
 *
 *      Строкой, а не упаковкой двоичного: так её ровно так же собирает
 *      двадцать строк на JavaScript, и нечему разойтись незаметно.
 *
 * ЧТО ЭТО ЗАКРЫВАЕТ: подслушивание (нечего слушать), повтор (номер и срок),
 * подделку запроса с чужого сайта (у чужой страницы нет ключа, а неявных
 * полномочий вроде кук и Basic здесь нет вовсе), подмену DNS (по той же
 * причине).
 *
 * ЧЕГО НЕ ЗАКРЫВАЕТ: тайну содержимого — оно идёт открытым текстом; и
 * АКТИВНОГО посредника, который подменит саму морду по пути к браузеру и
 * получит ключ сессии её же руками. Против второго помогает только обратный
 * прокси с TLS впереди либо запрет записи по умолчанию, ограничивающий ущерб.
 *
 * СЕКРЕТ ОБЯЗАН БЫТЬ СЛУЧАЙНЫМ. Перехватив nonce и одну подпись, его можно
 * подбирать без обращений к плате. 128 бит от генератора — да, придуманный
 * человеком пароль — нет.
 */
#ifndef COMBO_AUTH_H
#define COMBO_AUTH_H

#include "sha256.h"

#include <stdint.h>

/* Вызов: 4 байта времени, 4 счётчика, 16 подписи от них же.
 *
 * СЧЁТЧИК ОБЯЗАТЕЛЕН. Без него вызов выводится из одного времени в секундах, и
 * две вкладки, вошедшие в одну и ту же секунду, получают ОДИН И ТОТ ЖЕ ключ
 * сессии — а с ним и общее окно номеров, в котором они отвергают запросы друг
 * друга как повторы.
 *
 * Счётчик не тайна и состоянием на запрос не является: он один на плату, и
 * его наращивание ничего не выделяет. */
#define AUTH_NONCE_BYTES 24
#define AUTH_NONCE_HEX   (AUTH_NONCE_BYTES * 2)
#define AUTH_SESSIONS    4
#define AUTH_TTL_S       (12u * 60 * 60)    /* сколько живёт вызов */
#define AUTH_FAIL_LIMIT  16                 /* неудач подряд до задержки */
#define AUTH_FAIL_HOLD_S 2

/* Кэш от повторов, а НЕ таблица допуска. Потеря записи никого не пускает — она
 * лишь расширяет окно повтора с «никогда» до «пока свеж вызов». Поэтому
 * вытеснение не отказ в обслуживании, и истощать тут нечего: запись заводится
 * только по верной подписи, то есть тем, кто и так знает секрет. */
/* Окно от повторов, как в IPsec. Строго растущего номера НЕ хватает: морда
 * шлёт запросы внахлёст, и до платы они доходят в любом порядке — честный
 * запрос отвергался бы как повтор просто потому, что сосед обогнал его в
 * пути. Поэтому помним наибольший номер и битовую карту 64 предыдущих:
 * отставший в пределах окна принимается один раз, повтор — никогда. */
#define AUTH_WINDOW 64

typedef struct {
    uint8_t  nonce[AUTH_NONCE_BYTES];
    uint32_t seq;                           /* наибольший принятый номер */
    uint64_t seen;                          /* разряд i: номер seq-i уже был */
    uint32_t touched;                       /* для вытеснения самой давней */
    int      used;
} auth_slot_t;

typedef struct {
    char        secret[65];
    uint8_t     mkey[SHA256_SIZE];          /* подпись вызовов; свой при каждом запуске */
    auth_slot_t s[AUTH_SESSIONS];
    uint32_t    clock;                      /* растёт на каждой проверке */
    uint32_t    issued;                     /* сколько вызовов выдано */
    uint32_t    fails;
    uint32_t    hold_until_s;
} auth_t;

enum {
    AUTH_OK = 0,
    AUTH_OFF,           /* секрет не задан — проверки нет */
    AUTH_MISSING,       /* нет заголовков подписи */
    AUTH_BAD_NONCE,     /* вызов не наш или испорчен */
    AUTH_STALE,         /* вызов просрочен */
    AUTH_BAD_MAC,       /* подпись не сошлась */
    AUTH_REPLAY,        /* номер уже был или отстал дальше окна */
    AUTH_NO_SLOT,       /* нужна живая сессия, а её нет */
    AUTH_HELD           /* слишком много неудач подряд */
};

void auth_init(auth_t *a, const char *secret, const uint8_t seed[SHA256_SIZE]);
int  auth_on(const auth_t *a);              /* 1 — проверка включена */

/* Выдать вызов. out — не меньше AUTH_NONCE_HEX+1 байт. */
void auth_challenge(auth_t *a, uint32_t now_s, char *out);

/* Проверить запрос. body_hash — sha256 тела (для пустого тела тоже считается).
 * need_slot: 1 для действий, повтор которых НЕ безразличен (сброс привода,
 * включение записи) — им нужна уже заведённая сессия. */
int auth_check(auth_t *a, uint32_t now_s,
               const char *nonce_hex, const char *seq_str, const char *mac_hex,
               const char *method, const char *path,
               const uint8_t body_hash[SHA256_SIZE], int need_slot);

const char *auth_strerror(int rc);

/* Собрать ту же подпись, что ждёт плата. */
void auth_sign(const char *secret, const char *nonce_hex, uint32_t seq,
               const char *method, const char *path,
               const uint8_t body_hash[SHA256_SIZE], char *out_hex);

void auth_hex(const uint8_t *p, size_t n, char *out);

#endif
