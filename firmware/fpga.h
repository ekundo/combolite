/* Прошивка ПЛИС с ESP по SSPI: образ приезжает частями, проверяется
 * целиком и только потом пишется (sspi.c).
 *
 * ПОЧЕМУ ЧАСТЯМИ И В ПАМЯТЬ. Тело запроса у морды ограничено 32 КБ
 * (HTTP_MAX_BODY), а страниц у ПЛИС платы -- на 99 КБ, и сжимаются они плохо (93 КБ:
 * данные битстрима и так плотные). Писать прямо по мере прихода значило бы
 * стирать флеш, не видев файла целиком: оборвись загрузка -- плата осталась бы
 * с полуобразом. Поэтому части копятся в памяти блоками по 4 КБ (большой
 * сплошной кусок куча может и не дать), и стирание начинается, только когда
 * пришло всё и сошлась контрольная сумма.
 *
 * ОБРАЗ -- не .jed, а уже разобранные страницы: разбирает tools/combo.py на компьютере
 * (там же сверяется контрольная сумма JEDEC). Формат, все числа -- младшим
 * байтом вперёд:
 *    0  "CJED"
 *    4  версия (1), 0, длина заголовка (40), два байта
 *    8  код кристалла           12  USERCODE
 *   16  строка настроек, 8 байт 24  FEABITS, 2 байта; 2 байта ноль
 *   28  страниц                 32  CRC-32 страниц
 *   36  ноль                    40  страницы по 16 байт */
#ifndef COMBO_FPGA_H
#define COMBO_FPGA_H

#include <stddef.h>
#include <stdint.h>

#include "sspi.h"

#define FPGA_HDR 40

/* Часть образа с байта off. off == 0 начинает загрузку заново и обязан нести
 * заголовок; дальше части идут подряд. 0 -- принято, иначе msg объясняет. */
int  fpga_part(uint32_t off, const uint8_t *data, size_t n, const char **msg);

/* Выбросить пришедшее: образ из раздачи не сошёлся с манифестом. */
void fpga_drop(void);

/* Сколько пришло и сколько ждём. */
void fpga_progress(uint32_t *have, uint32_t *total);

/* Прошить пришедшее. Возврат -- коды SSPI_*; при отказе до стирания образ
 * остаётся в памяти, и можно повторить с другими флагами (SSPI_FORCE). */
int  fpga_flash(int flags, sspi_report *rep, const char **msg);

/* Есть ли SSPI на этой сборке и что отвечает кристалл; JSON для /api/fpga. */
int  fpga_json(char *out, int max);

/* Есть ли SSPI на этой сборке: только у такой платы ПЛИС обновляется сама. */
int  fpga_can_flash(void);

/* Что прошито последним: sha256 всего образа CJED (заголовок и страницы) --
 * тот же, что у образа в манифесте обновления. Запоминается после каждой
 * удачной прошивки с ESP, по обновлению и по combo.py fpga. ПЛИС, прошитую
 * мимо ESP (программатором по JTAG), ESP не видит: тогда хранится прежнее, и
 * обновление будет предложено лишний раз -- это безвредно. 0 -- известно,
 * -1 -- с ESP не прошивали ни разу. */
int  fpga_flashed(uint8_t sha[32]);

/* Брошенную загрузку выбросить через 5 минут: память у ESP одна на всех. */
void fpga_tick(uint32_t now_s);

/* --- от платформы: sspi_esp.c на плате. NULL -- SSPI нет. Выводы берутся
 *     на время прошивки и отпускаются после неё. */
const sspi_io *fpga_io_claim(void);
void           fpga_io_release(void);
/* Добавка к JSON /api/fpga, начиная с запятой; на плате -- ничего
 * (возвращает 0). */
int            fpga_io_extra(char *out, int max);

#endif
