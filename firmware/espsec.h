/* Секрет платы: хранение в NVS и восстановление через консоль.
 *
 * НА ЖЕЛЕЗЕ НЕ ПРОВЕРЕНО. Проверять при первом запуске.
 *
 * ОТКУДА БЕРЁТСЯ. Если задан CONFIG_COMBO_SECRET — берётся оттуда, и им
 * распоряжаетесь вы. Иначе плата создаёт 128 бит сама при первом запуске,
 * кладёт в NVS и печатает ОДИН раз. Дальше — только по команде: секрет в
 * журнале при каждой загрузке рано или поздно окажется в чужой переписке.
 *
 * ПОЧЕМУ ВОССТАНОВЛЕНИЕ ЧЕРЕЗ ПРОВОД. У того, кто дотянулся до платы руками,
 * и так есть всё: он вынет винт и прочитает его где угодно. Значит физический
 * доступ как корень доверия не стоит ничего, а любое восстановление по сети —
 * будь то окно после включения или кнопка в морде — это чёрный ход, которым
 * воспользуется кто угодно, дождавшись отключения электричества.
 *
 * Команды в мониторе:
 *   secret        показать текущий
 *   secret new    создать новый; все сессии умирают
 */
#ifndef COMBO_ESPSEC_H
#define COMBO_ESPSEC_H

#include <stddef.h>

/* Положить секрет в out. Вернуть 0, даже если секрета нет: тогда out пуст, и
 * проверка доступа окажется выключена — об этом кричит main_esp.c. */
int espsec_load(char *out, size_t max);

/* Зарегистрировать команды монитора. Без неё восстановление невозможно. */
void espsec_console(void);

#endif
