/* Обновление по воздуху: прошивка и статика.
 *
 * ЗАЧЕМ. Пока плата на шнурке, обновление — это idf.py flash. Стоит ей уехать
 * под стол или в корпус «Вектора», и шнурка нет: чтобы поправить строку в
 * морде, пришлось бы разбирать машину.
 *
 * ЧТО ОБНОВЛЯЕТСЯ. Две разные вещи, и обе нужны: сама прошивка (combolite.bin)
 * и статика морды (www.bin, образ SPIFFS). Одна без другой быстро расходится —
 * морда зовёт то, чего в прошивке ещё нет, или наоборот.
 *
 * ПРОШИВКА ПИШЕТСЯ В ЗАПАСНОЙ РАЗДЕЛ, не в тот, из которого работаем. Если она
 * не запустится, загрузчик вернётся к прежней: плата под столом не должна
 * становиться кирпичом от одной неудачной сборки. Со статикой так нельзя —
 * раздел под неё один, — поэтому неудачная запись портит морду до следующей
 * попытки; зато прошивка при этом цела и попытку принять сможет.
 *
 * ПОДПИСЬ ПРОВЕРЯЕТСЯ В КОНЦЕ. Мегабайт в памяти платы не держится, поэтому
 * данные пишутся потоком, а хеш считается по дороге. Пока он не сошёлся с
 * подписью, новый раздел не объявляется загрузочным и SPIFFS не
 * перемонтируется: не сошёлся — забыли, будто и не было.
 */
#ifndef COMBO_OTA_H
#define COMBO_OTA_H

#include <stddef.h>
#include <stdint.h>

enum { OTA_APP, OTA_WWW };

/* Открыть приём. what — OTA_APP или OTA_WWW, len — сколько байт обещано.
 * Возвращает 0 или отрицательное. */
int ota_begin(int what, size_t len);

/* Очередной кусок. Возвращает 0 или отрицательное; при ошибке приём закрыт. */
int ota_write(const uint8_t *buf, size_t n);

/* Закончить приём. ok — сошлась ли подпись и хватило ли байт. При ok != 0
 * прошивка объявляется загрузочной (перезагрузку делает вызывающий), иначе всё
 * написанное забывается. Возвращает 0 или отрицательное. */
int ota_finish(int ok);

/* Человеческое описание последней беды — для ответа наружу, по-английски. */
const char *ota_error(void);

/* Версия работающей прошивки — та самая строка, что кладёт в образ сборка и
 * что сравнивается с манифестом. */
const char *ota_version(void);

/* Какой раздел работает сейчас и цел ли он. Для /api/info: после обновления
 * полезно видеть, что плата и правда поднялась с новой прошивки. */
const char *ota_running(void);

/* Сказать загрузчику, что эта прошивка работает.
 *
 * Пока она этого не сказала, она испытательная: не дойди дело до этого вызова
 * — упади она при старте, зависни на сети, — при следующем включении
 * загрузится прежняя. Звать надо после того, как поднялись сеть и файловая
 * система, но ДО того, как сервер уйдёт в свой бесконечный цикл: иначе некому
 * будет сказать.
 *
 * Для прошивки, которая и так работает давно, вызов ничего не делает. */
void ota_mark_good(void);

/* Перезагрузиться. Отдельно от приёма, потому что ответ должен успеть дойти:
 * оборви мы соединение перезагрузкой, человек увидел бы «сеть недоступна» и не
 * узнал, приняла плата обновление или нет. */
void ota_reboot(void);

#endif
