/* Сеть, сохранённая на плате. Настройка без шнурка.
 *
 * ЗАЧЕМ. Сеть, зашитая при сборке через menuconfig, годится, лишь пока плата
 * на столе. Стоит поставить её в машину — а сеть сменить, переехать
 * или сменить пароль, — и настроить её станет нечем: чтобы записать новый
 * пароль, придётся доставать плату и подключать шнурок.
 *
 * КАК. Учётные данные лежат в NVS и перекрывают зашитые при сборке. Нет
 * сохранённых и нет зашитых — плата поднимает СВОЮ точку доступа и отдаёт ту же
 * морду в режиме настройки: человек подключается к ней с телефона, выбирает
 * сеть из списка и вводит пароль.
 *
 * ТУДА ЖЕ ПЛАТА УХОДИТ, ЕСЛИ НЕ СМОГЛА ПОДКЛЮЧИТЬСЯ. Иначе первая же смена
 * пароля на роутере превращала бы её в молчащую коробку: она бы вечно
 * перебирала попытки, а сказать об этом было бы некому.
 */
#ifndef COMBO_NETCFG_H
#define COMBO_NETCFG_H

#include <stddef.h>

/* Сеть, увиденная в эфире: столько, сколько нужно для выбора её человеком.
 *
 * Тип живёт здесь, а не в wifi.h, потому что нужен обоим: радио его наполняет,
 * сервер раскладывает в JSON. Тащить ради него в http.c весь wifi.h, полный
 * ESP-шных вещей, значило бы связать сервер с радио на пустом месте. */
typedef struct {
    char ssid[33];
    int  rssi;
    int  secure;                /* сеть с паролем */
} combo_net_t;

/* Что плата знает про свою сеть. Три состояния, и все три разные.
 *
 * Двух мало: если «забыть сеть» только очищает сохранённое, при старте плата
 * берёт ЗАШИТУЮ при сборке — по правилу «нет сохранённой, возьми зашитую», — и
 * как ни в чём не бывало возвращается в ту же сеть. Забыть её нечем, пока в
 * прошивке лежит рабочая.
 *
 * Разница смысловая: «ещё не решали» и «решили не подключаться» — не одно и то
 * же, и зашитая сеть годится только для первого. */
enum {
    NETCFG_NONE = 0,        /* решения нет: годится зашитая при сборке */
    NETCFG_HAVE = 1,        /* сеть выбрана человеком */
    NETCFG_FORGOTTEN = -1   /* сеть забыта НАРОЧНО: в настройку, и не спорить */
};

/* Что делать со всем этим при старте. */
enum {
    NETPLAN_SAVED = 0,      /* подключаться к сохранённой */
    NETPLAN_BUILTIN = 1,    /* к зашитой при сборке */
    NETPLAN_SETUP = 2       /* поднимать свою точку и ждать указаний */
};

/* Решение отделено от радио и от NVS нарочно: ошибиться в нём легко, а
 * последствия видны только на живой плате и не сразу: например, «забыть сеть»
 * откатывается к зашитой, и плата возвращается в ту же сеть, из которой её
 * только что увели.
 *
 * builtin — есть ли зашитая сеть в сборке. */
int netcfg_plan(int state, int builtin);

/* Показывать ли секрет на экране настройки. Только при первой настройке: плата
 * ещё ничья, и взять его человеку больше негде. Забыл сеть сам — секрет он уже
 * знает, и раздавать его точке, поднятой в чужом доме, незачем. */
int netcfg_show_secret(int state);

/* Взять сохранённую сеть, вернув одно из трёх состояний выше. */
int netcfg_load(char *ssid, size_t ssid_max, char *pass, size_t pass_max);

/* Сохранить и вернуть 0, либо отрицательное. Пустое имя означает «забыть». */
int netcfg_save(const char *ssid, const char *pass);

/* Забыть сохранённое: плата поднимется в режиме настройки — и зашитая при
 * сборке сеть её оттуда не уведёт. */
int netcfg_forget(void);

#endif
