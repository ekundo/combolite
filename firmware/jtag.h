/* JTAG к ПЛИС: автомат TAP и опознание кристалла.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Здесь нет ни одной строчки про ESP32: всё общение с
 * ногами спрятано за один вызов `pulse`. Это не украшение — автомат TAP легко
 * ошибается на один такт, и найти такую ошибку на живом кристалле почти
 * невозможно: он просто молчит. Отделённый от ног, автомат можно проверить без
 * кристалла, и там любое лишнее или недостающее состояние видно сразу.
 *
 * ДЛИНА IR У MachXO2 — ВОСЕМЬ БИТ. Ошибиться в ней нельзя: команда уедет не
 * туда, а кристалл не пожалуется.
 *
 * Все обращения начинаются и заканчиваются в Run-Test/Idle. Так их можно
 * ставить друг за другом, не помня, где TAP остался в прошлый раз.
 */
#ifndef COMBO_JTAG_H
#define COMBO_JTAG_H

#include <stdint.h>

/* Один такт TCK. Выставить TMS и TDI, щёлкнуть, вернуть TDO.
 *
 * TDO читается ДО фронта: кристалл выкладывает его по спаду предыдущего такта,
 * а TMS и TDI забирает по фронту. Перепутать эти два края — самая частая
 * ошибка в самодельном JTAG, и лечится она тем, что край здесь ровно один и
 * описан в одном месте. */
typedef struct {
    int (*pulse)(void *ctx, int tms, int tdi);
    void *ctx;
} jtag_io;

/* Пять тактов с TMS=1 приводят TAP в Test-Logic-Reset из ЛЮБОГО состояния —
 * это свойство самого автомата, а не соглашение. Шестой такт с TMS=0 уводит в
 * Run-Test/Idle, откуда работают все остальные вызовы. */
void jtag_reset(const jtag_io *io);

/* Сдвинуть команду в IR. Возврат в Run-Test/Idle. */
void jtag_ir(const jtag_io *io, uint8_t ir);

/* Сдвинуть данные в DR, младшим битом вперёд.
 *
 * `out` — что задвигаем, `in` — что вышло; любой из них может быть NULL.
 * Длина в БИТАХ, не в байтах: регистры JTAG сплошь и рядом не кратны восьми. */
void jtag_dr(const jtag_io *io, const uint8_t *out, uint8_t *in, int nbits);

/* Опознание кристалла.
 *
 * Сразу после Test-Logic-Reset в IR по стандарту стоит IDCODE, поэтому команду
 * задавать не нужно — достаточно сдвинуть 32 бита из DR. Это самая безопасная
 * проверка из возможных: она ничего не меняет в кристалле и годится как первый
 * признак того, что провода припаяны верно.
 *
 * ДВА РАЗНЫХ ВЫВОДА, их нельзя смешивать. Что код вообще ПРОЧИТАЛСЯ — это про
 * провода: TCK, TMS и TDI довели TAP до сдвига, TDO отдал 32 бита. КАКОЙ код
 * пришел — это уже про кристалл. Исправные провода к другому кристаллу не
 * должны выглядеть как неисправность.
 *
 * КОД — НЕ ИМЯ. Один и тот же код носят несколько приборов (у Lattice сорта ZE
 * и HE неразличимы, а «U»-варианты совпадают со следующим размером), поэтому
 * jtag_device_name() возвращает ПЕРЕЧЕНЬ, а не один прибор.
 *
 * ОТКУДА ЧИСЛА. Таблица Device ID Codes была в старых редакциях руководства
 * Lattice (TN1204); в нынешней, FPGA-TN-02155 ред. 4.6, ее уже нет, как нет и
 * в даташите FPGA-DS-02056-4.7 — оба проверены поиском по тексту. Поэтому коды
 * сверены по трем независимым источникам, и все три сошлись:
 *   1) файлы проектов Diamond (.xcf), куда Lattice сама пишет <IDCode> рядом с
 *      именем прибора: 0x012bc043 у LCMXO2-4000HC, 0x012bd043 у LCMXO2-7000HC,
 *      0x012b5043 у LCMXO2-7000HE;
 *   2) таблица openFPGALoader (src/part.hpp) — она же называет совпадения;
 *   3) edbg и usb-sniffer: 0x012bb043 = LCMXO2-2000HC.
 * Последнее сходится с кодом, прочитанным с живого кристалла, — то есть
 * источники проверены на известном ответе. */
uint32_t jtag_idcode(const jtag_io *io);

#define JTAG_IDCODE_LCMXO2_2000HC 0x012BB043u   /* он же LCMXO2-1200UHC */
#define JTAG_IDCODE_LCMXO2_4000HC 0x012BC043u   /* он же LCMXO2-2000UHC */
#define JTAG_IDCODE_LCMXO2_7000HE 0x012B5043u   /* он же LCMXO2-7000ZE   */
#define JTAG_IDCODE_LCMXO2_7000HC 0x012BD043u   /* он же LCMXO2-4000UHC  */

/* Код, с которым /api/jtag сверяет прочитанный (поле board). На плате стоит
 * LCMXO2-7000HE-4TG144C, но проводов JTAG к ПЛИС у модуля ESP нет
 * (jtag_fake.c), и сверка не выполняется. */
#define JTAG_IDCODE_BOARD JTAG_IDCODE_LCMXO2_4000HC

/* Перечень приборов с таким кодом или NULL, если код не из известных.
 * NULL — это «не знаю», а не «плохо»: прочитанный код все равно означает, что
 * провода живы, и печатать его надо в любом случае. */
const char *jtag_device_name(uint32_t idcode);

/* Опознать кристалл на живой плате: занять ноги, спросить, отпустить.
 *
 * НОГИ ОТПУСКАЮТСЯ ОБЯЗАТЕЛЬНО. Пока прошивка их не держит, они входы без
 * подтяжек, и разъём JTAG остаётся свободен для внешнего программатора. Если
 * оставить их выходами, программатор на том же разъёме упрётся в наши уровни,
 * а причина будет выглядеть как неисправность кабеля.
 *
 * Возвращает 0 и пишет `id`, либо отрицательное при ошибке.
 * На сборке без проводов JTAG — заглушка, см. `jtag_fake.c`. */
int jtag_probe(uint32_t *id);

#define JTAG_ENOHW (-1)         /* сборка без железа */

/* ПРОЗВОНКА ПРОВОДОВ, без участия автомата TAP.
 *
 * Когда опознание отдаёт нули, вопрос «кристалл не отвечает или провод не
 * припаян» неразрешим изнутри JTAG: в обоих случаях на TDO ноль. Но у линий в
 * покое есть известное поведение, и по нему они различаются.
 *
 * Каждая нога делается входом сперва с подтяжкой ВВЕРХ, потом ВНИЗ, и
 * запоминается, что прочиталось. Внутренние подтяжки ESP слабые, порядка
 * 45 кОм, поэтому всё, что на плате сильнее, их пересилит — и это и есть
 * признак:
 *
 *   TCK  на плате подтянут к земле, 4,7 кОм. Подключён — под нашей
 *        подтяжкой вверх читается НОЛЬ. Единица означает оборванный провод.
 *   TDO  у кристалла в третьем состоянии всюду, кроме сдвига, поэтому обязан
 *        следовать за нашей подтяжкой: вверх — единица. Ноль под подтяжкой
 *        вверх означает замыкание на землю, а на разъёме JTAG земляные выводы
 *        чередуются с сигнальными.
 *   TMS, TDI  у кристалла со слабой внутренней подтяжкой вверх. Ноль под нашей
 *        подтяжкой вверх — снова земля.
 *
 * Порядок в массивах: 0 TCK, 1 TMS, 2 TDI, 3 TDO. */
typedef struct {
    int up[4];
    int down[4];
} jtag_pins;

int jtag_check_pins(jtag_pins *p);

/* ПОИСК ЗАБЛУДИВШЕГОСЯ ПРОВОДА.
 *
 * Когда линия ведёт себя как висящая в воздухе, вопрос не «припаяна ли она», а
 * «куда она припаяна». Перебирать ноги по одной, каждый раз пересобирая
 * прошивку, — полчаса на попытку; здесь они опрашиваются все разом тем же
 * способом, что и в `jtag_check_pins`.
 *
 * Признак искомого: нога, которая держится в ЕДИНИЦЕ даже под нашей подтяжкой
 * вниз. Так ведут себя `TMS` и `TDI` — их держат внутренние подтяжки кристалла.
 * Свободная нога послушно следует за нами и даёт 1/0.
 *
 * Перебираются только ноги, у которых есть внутренние подтяжки: без них этим
 * способом не проверить.
 *
 * `n` на входе — сколько places в массивах, на выходе — сколько заполнено. */
int jtag_scan(int *pin, int *up, int *down, int *n);

/* УДЕРЖАТЬ УРОВНИ НА ВЫХОДАХ, чтобы их можно было померить вольтметром.
 *
 * Когда провода прозвонены, кристалл жив, а автомат не двигается, остаётся
 * вопрос, на который изнутри прошивки ответить нечем: доходят ли НАШИ уровни до
 * разъёма. Осциллограф увидел бы это сразу, но такт в полмегагерца не поймать
 * вольтметром — а постоянный уровень поймать можно.
 *
 * Держит `secs` секунд и отпускает ноги обратно во входы. Всё это время плата
 * занята: вызов возвращается только по окончании. */
int jtag_hold(int tck, int tms, int tdi, int secs);

/* ПРОЙТИ ПО АВТОМАТУ ВРУЧНУЮ и замереть, чтобы померить TDO вольтметром.
 *
 * Выдать `clocks` тактов с заданными TMS и TDI, затем держать уровни `secs`
 * секунд. Состояние TAP между вызовами СОХРАНЯЕТСЯ: отпущенный TCK уходит вниз
 * через подтяжку и фронтов не даёт, а без фронтов автомат не движется. Значит путь
 * можно пройти по шагам, разными вызовами, и в конце спокойно измерить.
 *
 * Зачем: в состоянии Shift-DR кристалл ОБЯЗАН вести TDO, и третий бит IDCODE
 * равен нулю. Ноль вольт на TDO там докажет, что автомат работает, а виновата
 * наша скорость или порядок краёв. Три вольта — что автомат стоит. */
int jtag_step(int tms, int tdi, int clocks, int secs);

/* ПОЛТАКТА В МИКРОСЕКУНДАХ. По умолчанию 1, то есть около 500 кГц.
 *
 * Ручка нужна не для скорости, а как ПРИБОР. Соединение с большим переходным
 * сопротивлением — непропай, окисел, волосок припоя — проводит постоянный ток
 * и на вольтметре выглядит исправным: прибор берёт микроамперы. А вход
 * кристалла с его ёмкостью такое соединение за микросекунду не перезарядит, и
 * фронт до кристалла не доходит.
 *
 * Отличить это от всего остального можно только замедлением: если на десяти
 * миллисекундах автомат оживает, дело в стыке, а не в логике. */
void jtag_speed(int half_us);

/* ПОИСК ЗАМЫКАНИЙ МЕЖДУ ЛИНИЯМИ.
 *
 * Если уровни на TCK, TMS и TDI задать ОДИНАКОВЫМИ, перемычка между соседними
 * выводами невидима — обе линии показывают одно и то же. А волосок припоя
 * между соседями с шагом 2,54 мм вполне возможен.
 *
 * Способ: одну линию ведём ВНИЗ как выход, остальные слушаем входами с
 * подтяжкой вверх. Любая, кто ушла в ноль вместе с ведомой, с ней соединена.
 * Кристаллу это безвредно: его входы и так терпят любые уровни, а TDO у него
 * выход только в состояниях сдвига, куда мы не заходим.
 *
 * Итог — матрица 4x4, порядок тот же: 0 TCK, 1 TMS, 2 TDI, 3 TDO.
 * `m[i][j]` = что прочиталось на линии j, когда вниз вели линию i. */
int jtag_bridges(int m[4][4]);

#endif
