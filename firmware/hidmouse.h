/* Отчёт USB-мыши в протоколе отчётов: где в нём кнопки, X, Y и колесо.
 *
 * ЗАЧЕМ. В загрузочном протоколе отчёт мыши -- три байта: кнопки, dx, dy.
 * Колесо четвёртым байтом кладут туда не все: первая rev4 (25.10.2026) слала
 * ровно три, и колесо на «Векторе» молчало. В протоколе отчётов колесо есть,
 * но раскладка у каждой мыши своя: номер отчёта впереди или нет, X и Y по 8,
 * 12 или 16 разрядов, кнопок от трёх до шестнадцати. Её и читаем из описателя
 * отчётов (HID 1.11, раздел 6.2.2).
 *
 * Переносимо: разбор проверяется на маке отдельным стендом, на плате его
 * зовёт mouse_esp.c. */
#ifndef COMBO_HIDMOUSE_H
#define COMBO_HIDMOUSE_H

#include <stdint.h>

typedef struct {
    uint8_t  id;            /* номер отчёта мыши; 0 -- номеров у устройства нет */
    uint16_t btn_off;       /* разряд первой кнопки от начала данных (за номером) */
    uint8_t  btn_n;         /* кнопок, не больше 3: у машины их три */
    uint16_t x_off, y_off, w_off;
    uint8_t  x_size, y_size, w_size;   /* разрядов; w_size 0 -- колеса нет */
} hidm_t;

/* Разобрать описатель отчётов. 0 -- нашлись X и Y в одном отчёте, -1 -- нет
 * (тогда остаётся загрузочный протокол). */
int hidm_parse(const uint8_t *d, int n, hidm_t *m);

/* Отчёт с конечной точки -> кнопки (разряд 0 левая, 1 правая, 2 средняя),
 * сдвиги в -127..127, колесо в -127..127 (от себя -- плюс, как у HID).
 * 0 -- это отчёт мыши, -1 -- чужой номер или короткий. */
int hidm_decode(const hidm_t *m, const uint8_t *r, int n,
                uint8_t *btn, int *dx, int *dy, int *wheel);

#endif
