/* Когда перебираться на другую точку доступа.
 *
 * Отдельно от wifi.c, потому что это АРИФМЕТИКА, а не работа с радио: её можно
 * проверить без всякого радио. Ошибиться тут легко и
 * дорого — плата либо мечется между двумя почти равными точками, разрывая
 * связь каждые полминуты, либо сидит на -91 дБм и не двигается.
 */
#ifndef COMBO_ROAM_H
#define COMBO_ROAM_H

#include <stdint.h>

/* ЦЕНА ПЕРЕХОДА РЕШАЕТ, КОГДА ПЕРЕХОДИТЬ, и она бывает двух разных величин.
 *
 * Своими силами переход стоит дорого: связь рвётся и собирается заново, а если
 * в этот миг шло применение, оно оборвётся. Ради такого стоит двигаться, только
 * когда нынешняя точка уже мешает работать, и только за большой выигрыш.
 *
 * Когда сеть умеет 802.11v, она переводит нас сама, сменой ассоциации:
 * соединения переживают переход, и платить за него нечем. Тогда терпеть плохую
 * точку незачем — пороги мягче, а пауза короче. Это не «настройка на вкус», а
 * прямое следствие: дорогое действие делают редко и наверняка, дешёвое — по
 * мере надобности. */
#define ROAM_POOR      (-75)    /* хуже этого связь уже мешает работать */
#define ROAM_GAIN       12      /* у соседних замеров разброс 5-6 дБ */
#define ROAM_PAUSE_S    300     /* чтобы две равные точки не перекидывали нас */

#define ROAM_POOR_SOFT (-65)    /* мягкий переход: можно и не терпеть */
#define ROAM_GAIN_SOFT   8      /* но всё ещё больше дрожания */
#define ROAM_PAUSE_SOFT  60

/* Перебираться ли. cur — сигнал текущей точки, best — лучшей найденной,
 * same — это та же самая точка, since_s — сколько секунд прошло с прошлого
 * перехода (большое число, если его не было вовсе), soft — переход сделает
 * сама сеть, то есть без разрыва. */
int roam_decide(int cur, int best, int same, int64_t since_s, int soft);

#endif
