/* ------------------------------------- образ дискеты .fdd и перевод с винта
 *
 * Отдельным модулем, а не внутри морды: перевод переписывает дискету целиком,
 * и ошибка здесь стирает данные. Отсюда его берёт и морда, и node.
 *
 * Разметка .fdd, снятая с настоящих образов (os-t72, co-t72f, RDS-3.10, T72):
 * 82 цилиндра × 2 стороны × 5 секторов по 1024 байта = 839680 байт, они же
 * 1640 секторов по 512. Первые 80 секторов — системные дорожки 0..7, дальше
 * каталог и данные. Каталог найден на секторе 80 во всех проверенных образах.
 *
 * На винте всё то же самое, только системные дорожки лежат ОДИН раз, в
 * секторах 2..81, и общие на все дискеты. Оттого перевод — это
 * простой перенос 1560 секторов со сдвигом в 80.
 *
 * Одно расхождение существенное. На винте у дискеты 390 блоков данных
 * (2..391), а в 1640 секторов помещается 388 (2..389): блок b лежит на секторе
 * 80 + b*4, и блок 389 занимает последние четыре сектора образа. Дискету,
 * которая задела блоки 390 или 391, в .fdd не уложить — на настоящем винте
 * таких четыре из 324. Отказ понятной фразой лучше молчаливой потери хвоста.
 */

export const FDD_SYS = 80;              /* зарезервированные дорожки 0..7 */

/* Два размера образа, оба встречаются в жизни.
 *
 * Обычный — 164 дорожки, 820 КБ: так сделаны 94 образа из 105 под рукой. В него
 * входят блоки 0..389.
 *
 * Крупный — 166 дорожек (83 цилиндра), 830 КБ: так сделана T72.fdd, официальная
 * раздача МикроДОС. Нужен, когда дискета заняла блоки 390 или 391, которых на
 * винте 392 (DSM=187h), а в обычный образ влезает 390. */
export const FDD_SECS     = 1640;
export const FDD_BIG_SECS = 1660;

export const FDD_CPM = 1560;            /* каталог и блоки 0..389 */
export const HDD_CPM = 1568;            /* каталог и блоки 0..391 — как на винте */

export const FDD_MAX_BLK = 389;         /* влезает в обычный образ */
export const HDD_MAX_BLK = 391;         /* столько даёт DPB и держит винт */

/* Сколько секторов от каталога брать и какой образ из них выйдет. */
export const cpm_size = top => top > FDD_MAX_BLK ? HDD_CPM : FDD_CPM;
export const fdd_size = top => top > FDD_MAX_BLK ? FDD_BIG_SECS : FDD_SECS;

/* Чем засыпаны системные дорожки у дискеты без системы. Проверено: у co-t72f
 * все 40960 байт — E5h, и это же кладёт форматирование. */
export const FDD_FILL = 0xE5;

/* Относительным путём, а не от корня: так он разрешается и в браузере (сосед
 * по каталогу), и в node, где морду поднимают проверки. */
import { fill } from './disk.mjs';

const SEC = 512, DIR_SECS = 8;

/* Отказ с тем же устройством, что у раскладчика: готовая английская строка
 * плюс ключ и подставленное — чтобы морда могла перевести. См. www/disk.mjs. */
export class FddError extends Error {
  constructor(key, ...args) { super(fill(key, args)); this.key = key; this.args = args }
}

/* Старший блок, на который ссылается каталог. Нужен, чтобы отказать до того,
 * как что-то записано. */
export function top_block(dir) {
  let top = 0;
  for (let i = 0; i < dir.length; i += 32) {
    const b0 = dir[i];
    if (b0 > 0x1F) continue;            /* не запись файла */
    for (let j = 0; j < 8; j++) {
      const b = dir[i + 16 + j * 2] | (dir[i + 17 + j * 2] << 8);
      if (b > top) top = b;
    }
  }
  return top;
}

/* Похоже ли это на каталог CP/M. Бросить в морду можно что угодно, а записать
 * это на дискету — испортить её молча. Признак простой и достаточный: каждая
 * запись либо свободна, либо принадлежит области 0..31, и хоть одна занята. */
export function looks_like_dir(dir) {
  let files = 0;
  for (let i = 0; i < dir.length; i += 32) {
    const b0 = dir[i];
    if (b0 === 0xE5) continue;
    if (b0 > 0x1F) return false;
    /* Имени мало быть на месте — оно обязано быть именем. Иначе сплошные нули
       сойдут за каталог, полный файлов области 0 с пустыми именами: байт 00h
       это законная область пользователя, и одной проверки первого байта не
       хватает. Старший бит в имени — признак, при сравнении он снимается. */
    let blank = true;
    for (let k = 1; k <= 11; k++) {
      const c = dir[i + k] & 0x7F;
      if (c < 0x20 || c > 0x7E) return false;
      if (c !== 0x20) blank = false;
    }
    if (blank) return false;
    files++;
  }
  return files > 0;
}

/* Собрать .fdd: системные дорожки плюс каталог с данными.
 *
 * sys — 80 секторов или null; null значит пустые дорожки, и это НЕ то же самое,
 * что нули: формат засыпает их E5h.
 */
export function to_fdd(cpm, sys) {
  const secs = cpm.length / SEC;
  if (secs !== FDD_CPM && secs !== HDD_CPM)
    throw new FddError('the CP/M area must be %1 or %2 sectors', FDD_CPM, HDD_CPM);
  if (sys && sys.length !== FDD_SYS * SEC)
    throw new FddError('the system tracks must be %1 sectors', FDD_SYS);

  /* Размер выбирается по СОДЕРЖИМОМУ, а не по длине переданного куска: крупный
     образ только тогда, когда каталог и правда достаёт до блоков 390-391.
     Незачем всякую дискету раздувать до 830 КБ, а хвост из E5h за последним
     блоком выбрасывается сам. */
  const want = fdd_size(top_block(cpm.subarray(0, 8 * SEC)));
  const out = new Uint8Array(want * SEC).fill(FDD_FILL);
  if (sys) out.set(sys, 0);
  out.set(cpm.subarray(0, Math.min(cpm.length, (want - FDD_SYS) * SEC)),
          FDD_SYS * SEC);
  return out;
}

/* Разобрать .fdd на то, что кладётся на дискету.
 *
 * Системные дорожки ОТБРАСЫВАЮТСЯ. На винте они общие и лежат один раз: у
 * дискет со второй по последнюю эти 80 секторов — вовсе не их собственные, а
 * хвост предыдущей дискеты, и записать их туда значило бы её испортить.
 *
 * Размер берём не на веру: у образов встречается и 1660 секторов. Лишний хвост
 * отбрасываем, но только если каталог на него не ссылается, а короткий
 * дописываем E5h.
 */
export function from_fdd(img) {
  if (img.length % SEC)
    throw new FddError('the image length is not a multiple of 512');
  const secs = img.length / SEC;
  if (secs < FDD_SYS + DIR_SECS)
    throw new FddError('the image is too short: %1 sectors', secs);

  const dir = img.subarray(FDD_SYS * SEC, (FDD_SYS + DIR_SECS) * SEC);
  if (!looks_like_dir(dir))
    throw new FddError('no CP/M directory at sector 80 — not a disk image?');

  /* Каталог, ссылающийся дальше края образа, — испорченный образ, а не просто
     непривычный; про это говорим отдельно и раньше. */
  const top = top_block(dir);
  if (FDD_SYS + (top + 1) * 4 > secs)
    throw new FddError('the directory points past the end of the image (block %1)', top);
  /* Предел здесь ВИНТОВОЙ, а не дискетный: кладём-то на винт, а там 392 блока.
     Образ на 166 дорожек с блоком 391 ложится целиком. */
  if (top > HDD_MAX_BLK)
    throw new FddError('the image uses block %1, past %2 — more than a disk here holds',
                       top, HDD_MAX_BLK);

  /* Отдаём всегда винтовой длины: хвост за блоком 389 засыпан E5h, и дискета
     после приёма выходит чистой целиком, без остатков прежней. */
  const cpm = new Uint8Array(HDD_CPM * SEC).fill(FDD_FILL);
  const take = Math.min(HDD_CPM, secs - FDD_SYS);
  cpm.set(img.subarray(FDD_SYS * SEC, (FDD_SYS + take) * SEC), 0);
  return { cpm, dropped: secs - FDD_SYS - take };
}

/* Имя для скачанного образа: по метке, если она есть. */
/* Метку набирал человек, а имя пойдёт в файловую систему.
 *
 * Выбрасывается только то, чего имя файла и правда не терпит: ОБА разделителя
 * пути и управляющие знаки. Двоеточие, звёздочка, вопрос и вертикальная черта
 * остаются — macOS их принимает, и портить метку за чужую систему незачем.
 * Пробелы и кириллица остаются тем более: обратно метка приходит ИЗ ИМЕНИ
 * скачанного образа, и с заменой на тире «Games 2» после круга стало бы
 * «Games-2».
 *
 * ОБРАТНАЯ КОСАЯ ЗДЕСЬ НЕ ПРО ВКУСЫ WINDOWS. Из списка запретов это
 * единственный знак, который меняет не вид имени, а его СМЫСЛ: метка «..\..\x» превращается в путь наверх, и
 * имя, придуманное для одного файла, начинает указывать на другое место.
 * Двоеточие такого не делает, а разделитель делает — потому и чистится, как
 * прямая косая, независимо от того, чья система его примет.
 *
 * Пустая строка означает «метка в имя не годится» — звать будем по номеру. */
export const safe_label = label =>
  String(label || '')
    .replace(/[\u0000-\u001F/\\]+/g, ' ')
    .replace(/\s+/g, ' ')
    .replace(/^[.\s]+|[.\s]+$/g, '');

export function fdd_name(n, label) {
  const safe = safe_label(label);
  /* Без метки имя строится из номера, и номер шестнадцатеричный — как везде в
     морде и как их зовёт сам «Вектор». Без «h»: в морде её тоже нет нигде.
     Три знака хватает — дисков меньше 1000. */
  return safe ? `${safe}.fdd`
              : `disk-${n.toString(16).toUpperCase().padStart(3, '0')}.fdd`;
}
