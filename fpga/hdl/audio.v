// Звуковой выход: цифровой ABC-микшер и сигма-дельта модулятор.
//
// Резистивное смешивание заменено арифметикой. Соотношения те же, что в
// оригинале Syntal'а:
//     L = A + C/2      R = B + C/2
// Записанные как 2A + C и 2B + C, они дают ту же форму сигнала без деления.
//
// В резистивной схеме узел L — делитель: A через 10к, C через 20к, нагрузка 10к
// на землю, то есть (2A + C)/5. Ослабление там — побочный эффект схемы смешивания, а не
// замысел, поэтому цифрой оно не воспроизводится.
//
// ЗАПАС ПО ГРОМКОСТИ ОСТАВЛЕН СОЗНАТЕЛЬНО. Максимум 2A + C равен 765 при
// разрядности 10, то есть 75 процентов шкалы. Оставшаяся четверть — место под
// то, ради чего вообще взята FPGA: второй AY, ковокс, бипер. Так же поступает
// svofski в soundcodec.v, сводя AY, бипер и ковокс в 16-разрядную сумму.
//
// БИПЕР МАШИНЫ. Вход `beep` — выход таймера ВИ53 самого «Вектора», выведенный на
// разъём ВУ доработкой машины. Смешивается цифрой, а не резистором: уровень
// задаётся точно и подстраивать нечего. Вес по умолчанию 255, то есть ровно один
// полноразмерный канал AY, и он ровно занимает оставленный запас: максимум суммы
// становится 765 + 255 = 1020 из 1023. Если бипер окажется громким или тихим,
// правится одним параметром.
//
// ЗВУК МАШИНЫ БЕЗ ВЫВОДА `beep`. Контакта 42 на ПЛИС нет, таймер
// эмулируется прослушиванием шины (vi53.v): три канала ВИ53 и разряд PC0 ВВ55 --
// четыре равных источника по VI_GAIN = 63, вместе 252, в том же запасе. Внешний
// `beep`, если его подать, главнее: занимает запас целиком.
// Каналы ВИ53 считаются по НУЛЮ: в покое (после сброса, в режимах 1 и 5, до
// первой записи) их выходы стоят в единице, и счёт по единице давал бы на
// выходе постоянную 189 из 1023 -- в машине её снимает разделительный
// конденсатор, у нас она шумела бы сигма-дельтой в тишине. Знак звука на слух
// не различить. PC0 в покое нуль, его считаем по единице.

`default_nettype none

// ------------------------------------------------------- сигма-дельта, 1 порядок
// Модулятор с переносом: накопитель складывается сам с собой плюс уровень, а
// наружу идёт перенос. Среднее значение выхода строго равно level / 2**W, и это
// не приближение: за любое окно ровно 2**W тактов при постоянном входе перенос
// случается ровно level раз, независимо от начального остатка.
module audio_sd #(parameter W = 10) (
    input  wire         clk,
    input  wire         reset,
    input  wire [W-1:0] level,
    output reg          pdm
);

reg  [W-1:0] accu;
wire [W:0]   sum = {1'b0, accu} + {1'b0, level};

always @(posedge clk) begin
    if (reset) begin
        accu <= {W{1'b0}};
        pdm  <= 1'b0;
    end
    else begin
        accu <= sum[W-1:0];
        pdm  <= sum[W];
    end
end

endmodule

// ------------------------------------------------------------- ABC и два канала
// SPLIT = 1 -- сверка эмуляции ВИ53 с настоящим (если подан вход `beep`):
// слева только бипер машины, справа только наш ВИ53, AY не звучит. Один и тот
// же такт у двух таймеров -- ноты на слух и на анализаторе совпадают; свой
// кварц -- биение на длинной ноте.
module audio_out #(parameter BEEP_GAIN = 255, parameter VI_GAIN = 63,
                   parameter SPLIT = 0) (
    input  wire       clk,
    input  wire       reset,
    input  wire [7:0] ch_a,
    input  wire [7:0] ch_b,
    input  wire [7:0] ch_c,
    input  wire       beep,        // ВИ53 «Вектора», уровень с разъёма
    input  wire [2:0] vi,          // эмулированный ВИ53, три канала (vi53.v)
    input  wire       pc0,         // разряд PC0 ВВ55, оттуда же
    output wire       pdm_l,
    output wire       pdm_r
);

localparam W = 10;

wire [2:0]   vi_n     = {2'b00, ~vi[0]} + {2'b00, ~vi[1]} + {2'b00, ~vi[2]} + {2'b00, pc0};
wire [W-1:0] vi_add   = vi_n * VI_GAIN[W-1:0];
wire [W-1:0] beep_add = beep ? BEEP_GAIN[W-1:0] : vi_add;

wire [W-1:0] mix_l = SPLIT ? (beep ? BEEP_GAIN[W-1:0] : {W{1'b0}})
                   : {1'b0, ch_a, 1'b0} + {2'b00, ch_c} + beep_add;  // 2A + C
wire [W-1:0] mix_r = SPLIT ? vi_add
                   : {1'b0, ch_b, 1'b0} + {2'b00, ch_c} + beep_add;  // 2B + C

audio_sd #(.W(W)) sd_l (.clk(clk), .reset(reset), .level(mix_l), .pdm(pdm_l));
audio_sd #(.W(W)) sd_r (.clk(clk), .reset(reset), .level(mix_r), .pdm(pdm_r));

endmodule

`default_nettype wire
