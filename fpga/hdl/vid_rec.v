// Журнал палитры: что машина писала в порты видео, по строкам её растра.
//
// ЗАЧЕМ. Кадр машины 50 Гц, наш VGA -- 60, и строку, которую мы показываем,
// машина показывала в другой момент. Палитру меняют посреди кадра и даже
// посреди строки (мультиколор). Значит для каждой строки машины
// нужно знать, какой палитра была в её начале и что в ней менялось по ходу.
// Строки САМОСТОЯТЕЛЬНЫЕ -- снимок на начало строки плюс
// события, так что проигрыватель (vid_play.v) может взять любую строку в любой
// момент, не ведя палитру от верха кадра.
//
// ЧТО ЛОВИМ -- только записи в порты, других писателей у видео нет:
//   00  управляющее слово ВВ55: с D7 = 1 обнуляет порты A и B;
//   02  порт B: номер бордюра (3..0) и режим 512 (4) -- событие, если сменился;
//   03  порт A: прокрутка, но и строка клавиатуры -- берётся раз в кадр, в
//       момент, когда её читает машина (frame_stb, vid_raster.v);
//   0C..0F  палитра -- событие всегда.
//
// В КАКУЮ ЯЧЕЙКУ ПАЛИТРЫ. У «Вектора» -- в ячейку цвета под лучом, на бордюре и
// в обратном ходе -- в номер бордюра. Здесь так:
//   * запись ВНЕ картинки -- в номер бордюра, как у машины; регистратор ведёт
//     по ней свою палитру, а она уходит в снимки;
//   * запись В КАРТИНКЕ -- ячейку узнаёт проигрыватель при показе, у точки,
//     которую рисует в этом месте строки (vid_play.v). Здесь её не знают:
//     событие уходит с пометкой «под лучом» (разряд 17), а своя палитра НЕ
//     трогается -- иначе снимки следующих строк легли бы в чужую ячейку.
//     Нести такие записи на следующие строки -- забота проигрывателя.
// Картинка -- строки PIC_LINE0..+255 и такты POS_PIC0..+127 растра машины; эти
// же числа у проигрывателя, иначе он и регистратор разойдутся в том, где
// кончается бордюр. Ячейку событие не несёт: у записи вне картинки её берут из
// номера бордюра, который проигрыватель ведёт по тем же событиям порта B.
//
// ПРИЗНАК КАДРА. Разряд 10 слова 8 -- чётность кадра машины, в котором
// записана строка: проигрыватель по его смене видит шов двух кадров машины в
// одном своём и сбрасывает перенос записей «под лучом».
//
// ПАМЯТЬ -- блочная, запись в 50 МГц, чтение проигрывателем в 40 МГц:
//   журнал: {строка, номер 0..15} -> {палитра/порт B, место 8, значение 8};
//           312 x 16 слов по 18 разрядов -- 10 блоков;
//   снимки: строка x 9 слов -> слова 0..7 -- ячейки палитры парами
//           {2i+1, 2i}, слово 8 -- {кадр 1, событий 5, порт B 5} на начало
//           строки;
//           312 x 9 слов по 18 -- 6 блоков. Число событий известно только в
//           конце строки, поэтому слово 8 пишется на следующем line_stb.
// 16 событий на строку -- худший случай, не число из программ: OUT занимает 12
// тактов, строка -- 192, и 12 делит 192 нацело. Семнадцатое не придёт; если придёт (сбой растра) -- ovf.
`default_nettype none

module vid_rec #(
    parameter [8:0] PIC_LINE0 = 9'd40,     // как у vid_play.v
    parameter [7:0] POS_PIC0  = 8'd28,     // как у vid_play.v, замер BORD
    parameter [7:0] PAL_ADV   = 8'd5       // запись в палитру -- на столько тактов раньше
) (
    input  wire        clk,
    input  wire        reset,
    input  wire        iowr_reg,      // vu_bus.v
    input  wire [7:0]  port,
    input  wire [7:0]  din,
    input  wire        rast_ok,       // vid_raster.v
    input  wire        line_stb,
    input  wire [8:0]  line_no,
    input  wire [7:0]  pos,
    input  wire        frame_stb,
    output reg  [7:0]  scroll = 8'hFF,
    // чтение проигрывателем
    input  wire        rclk,
    input  wire        rce,           // разрешение такта чтения: у vid_play в 50 Гц -- через такт
    input  wire [12:0] ev_raddr,
    output reg  [17:0] ev_q,
    input  wire [11:0] sn_raddr,
    output reg  [17:0] sn_q,
    output reg  [7:0]  ovf = 8'd0,
    // палитра для снимка экрана (ide_remote.v, 0x57): ячейка pal_ra, тактом
    // позже; номер 16 -- порт B {0, 0, 0, режим 512, бордюр 3..0}. Это
    // палитра, какую ведёт регистратор: по записям вне картинки. Запись в порт
    // под лучом (мультиколор) в неё не попадает -- на снимке одна палитра и
    // один режим на кадр. Дальше в том же чтении -- журнал записей в порты
    // (раздел «журнал записей» ниже): 17 -- номер следующей записи журнала,
    // 18 -- счёт кадров, 1024..2047 -- сам журнал.
    input  wire [10:0] pal_ra,
    output wire [7:0]  pal_rd,
    input  wire        lg_hold,       // идёт выдача (ide_remote.v) -- журнал стоит
    // события растра в тот же журнал (vid_raster.v, dbg_*): порт F0 + вид
    input  wire        rd_stb,
    input  wire [1:0]  rd_kind,
    input  wire [7:0]  rd_a,
    input  wire [7:0]  rd_b
);

// ------------------------------------------------------------ порты
reg [7:0] pal [0:15];
reg [7:0] pa = 8'h00, pb = 8'h00;
integer k;
initial for (k = 0; k < 16; k = k + 1) pal[k] = 8'h00;

wire is_pal  = iowr_reg && port[7:2] == 6'b000011;
wire is_pb   = iowr_reg && port == 8'h02;
wire is_ctl  = iowr_reg && port == 8'h00 && din[7];
wire [7:0] pb_new = is_ctl ? 8'h00 : din;
wire pb_evt  = (is_pb | is_ctl) && pb_new[4:0] != pb[4:0];

// ------------------------------------------------------------ память
// Журнал 4992 x 18 и снимки 2808 x 18 -- банками 1024 x 9, каждый ровно в
// один блок EBR (bram.v; почему не одним массивом -- там же): журнал -- пять
// банков по глубине на две половины слова, 10 блоков; снимки -- три, 6 блоков.
// Банк чтения запоминается вместе с адресом. Снимок выходит на такт позже
// адреса, журнал -- на ДВА: после выбора банка из пяти стоит ещё триггер, иначе
// выбор плюс место события в vid_play.v не влезают в 25 нс (по Diamond
// 24,95 нс, 13 уровней).

reg        ev_we = 1'b0;
reg [12:0] ev_wa;
reg [17:0] ev_wd;
reg        sn_we = 1'b0;
reg [11:0] sn_wa;
reg [17:0] sn_wd;

wire [5*18-1:0] ev_bq;
wire [3*18-1:0] sn_bq;
reg  [2:0]      ev_rb = 3'd0;
reg  [1:0]      sn_rb = 2'd0;
genvar gb, gh;
generate
    for (gb = 0; gb < 5; gb = gb + 1) begin : g_ev
        for (gh = 0; gh < 2; gh = gh + 1) begin : g_h
            bram_sdp #(.AW(10), .DW(9)) b (
                .wclk(clk), .we(ev_we && ev_wa[12:10] == gb), .wa(ev_wa[9:0]),
                .wd(ev_wd[9*gh +: 9]),
                .rclk(rclk), .re(rce), .ra(ev_raddr[9:0]), .q(ev_bq[18*gb + 9*gh +: 9]));
        end
    end
    for (gb = 0; gb < 3; gb = gb + 1) begin : g_sn
        for (gh = 0; gh < 2; gh = gh + 1) begin : g_h
            bram_sdp #(.AW(10), .DW(9)) b (
                .wclk(clk), .we(sn_we && sn_wa[11:10] == gb), .wa(sn_wa[9:0]),
                .wd(sn_wd[9*gh +: 9]),
                .rclk(rclk), .re(rce), .ra(sn_raddr[9:0]), .q(sn_bq[18*gb + 9*gh +: 9]));
        end
    end
endgenerate
always @(posedge rclk) if (rce) begin
    ev_rb <= ev_raddr[12:10];
    sn_rb <= sn_raddr[11:10];
    ev_q  <= ev_bq[18*ev_rb +: 18];
end
always @(*) sn_q = sn_bq[18*sn_rb +: 18];

// ------------------------------------------------------------ строка
reg  [8:0] cur = 9'd0, prev = 9'd0;
reg        cur_ok = 1'b0, prev_ok = 1'b0;
reg  [4:0] n = 5'd0, n_prev = 5'd0;
reg  [4:0] pb0 = 5'd0, pb0_prev = 5'd0;
reg        fpar = 1'b0, fpar_cur = 1'b0, fpar_prev = 1'b0;   // чётность кадра машины

// Место записи: в картинке или нет. Разность по модулю 312 строк не нужна:
// картинка целиком внутри кадра (40 + 256 < 312).
//
// ЗАПИСЬ В ПАЛИТРУ СРАБАТЫВАЕТ НА PAL_ADV ТАКТОВ РАНЬШЕ записи в порт B того
// же OUT -- так в эмуляторе v06x (src/board.cpp: commit_time_pal =
// commit_time - 20, 20 тактов 12 МГц = 5 тактов процессора, подогнано по тесту
// bord2). Без этой поправки тест BORD2 даёт ровные края чёрного провала (точки
// 52 и 124), а у v06x они ступенькой: 42/53 и 114/125 -- запись палитры на
// такте 54 срабатывает на точке 2 x (54 - 5 - 28) = 42.
// Граница картинки POS_PIC0 снята тестом BORD по порту B, поэтому у записи в
// палитру и место, и признак «в картинке» -- по такту pal_pos; запись в
// первые PAL_ADV тактов строки считаем тактом 0.
wire [7:0] pal_pos = (pos >= PAL_ADV) ? pos - PAL_ADV : 8'd0;
wire [8:0] pic_row = cur - PIC_LINE0;
wire [7:0] pic_pos = pal_pos - POS_PIC0;
wire       in_pic  = (cur >= PIC_LINE0) && (pic_row < 9'd256) &&
                     (pal_pos >= POS_PIC0) && (pic_pos < 8'd128);
// Шаг записи снимка: 1..8 -- слова 0..7, 9 -- слово 8 прошлой строки. Палитра
// пишется в снимок прямо из рабочей, за восемь тактов после начала строки:
// запись в порт, попавшая в эти 160 нс, окажется и в снимке, и в журнале, --
// проигрыватель применит её дважды, с тем же итогом.
reg  [3:0] sq = 4'd0;

wire [11:0] base_cur  = {cur, 3'b000} + {3'b000, cur};     // cur * 9
wire [11:0] base_prev = {prev, 3'b000} + {3'b000, prev};

// ------------------------------------------------------------ журнал записей
// ДИАГНОСТИКА. Чтобы увидеть, где стоял луч, когда машина писала в порт, -- кольцо на
// 128 последних записей в 00 (с D7), 02 и 0C..0F, по 8 байт:
//   0  значение;
//   1  {в картинке, порт 00, порт 02, порт B до записи 4..0};
//   2  такт строки pos;   3  строка cur 7..0;
//   4  {строка опознана, растр опознан, чётность кадра, 0000, cur 8};
//   5  счёт кадров;       6  номер порта;   7  порядковый номер записи.
// Туда же -- события растра (vid_raster.v): «номер порта» F0..F2, значение и
// байт 1 -- два числа события (разбор -- tools/combo.py palog). Событие растра,
// пришедшее, пока пишется прежняя запись, ждёт в rd_pend.
// Пока ESP читает (lg_hold), журнал не пишется: иначе кольцо поедет под чтением.
// Блок EBR -- последний свободный из 26.
reg  [6:0]  lg_wp = 7'd0;
reg  [7:0]  lg_seq = 8'd0, lg_frames = 8'd0;
reg  [2:0]  lg_b = 3'd0;
reg         lg_on = 1'b0;
reg  [63:0] lg_e = 64'd0;
reg         lg_we = 1'b0;
reg  [9:0]  lg_wa = 10'd0;
reg  [7:0]  lg_wd = 8'd0;
wire [7:0]  lg_q;
reg         rd_pend = 1'b0;
reg  [1:0]  rdp_kind = 2'd0;
reg  [7:0]  rdp_a = 8'd0, rdp_b = 8'd0;
bram_sdp #(.AW(10), .DW(8)) lg_mem (
    .wclk(clk), .we(lg_we), .wa(lg_wa), .wd(lg_wd),
    .rclk(clk), .re(1'b1), .ra(pal_ra[9:0]), .q(lg_q));

reg  [7:0] pal_rd_r = 8'h00;
reg        lg_sel = 1'b0;
always @(posedge clk) begin
    lg_sel   <= pal_ra[10];
    pal_rd_r <= !pal_ra[4]           ? pal[pal_ra[3:0]]
              : pal_ra[1:0] == 2'd0 ? {3'b000, pb[4:0]}
              : pal_ra[1:0] == 2'd1 ? {1'b0, lg_wp}
              : pal_ra[1:0] == 2'd2 ? lg_frames : 8'h00;
end
// Байт журнала -- прямо с выхода блока: через ещё один триггер он опоздал бы к
// ESP (байт нужен через три такта после предыдущего, ide_remote.v).
assign pal_rd = lg_sel ? lg_q : pal_rd_r;

always @(posedge clk) begin
    ev_we <= 1'b0;
    sn_we <= 1'b0;

    if (is_pal && !in_pic) pal[pb[3:0]] <= din;   // в картинке ячейка неизвестна
    if (iowr_reg && port == 8'h03) pa <= din;
    if (is_ctl) pa <= 8'h00;
    if (is_pb | is_ctl) pb <= pb_new;
    if (frame_stb) scroll <= pa;

    if (line_stb) begin
        prev     <= cur;     prev_ok  <= cur_ok;
        n_prev   <= n;       pb0_prev <= pb0;
        fpar_prev <= fpar_cur;
        cur      <= line_no; cur_ok   <= rast_ok;
        if (line_no == 9'd0) fpar <= ~fpar;
        fpar_cur <= (line_no == 9'd0) ? ~fpar : fpar;
        n        <= 5'd0;
        pb0      <= pb[4:0];
        sq       <= 4'd1;
    end
    else begin
        // снимок: слова 0..7 этой строки, потом слово 8 прошлой
        if (sq != 4'd0) begin
            if (sq <= 4'd8) begin
                sn_we <= cur_ok;
                sn_wa <= base_cur + {8'd0, sq - 4'd1};
                sn_wd <= {2'b00, pal[{sq[2:0] - 3'd1, 1'b1}], pal[{sq[2:0] - 3'd1, 1'b0}]};
                sq    <= sq + 4'd1;
            end
            else begin
                sn_we <= prev_ok;
                sn_wa <= base_prev + 12'd8;
                sn_wd <= {7'd0, fpar_prev, n_prev, pb0_prev};
                sq    <= 4'd0;
            end
        end

    end

    // событие: палитра всегда, порт B -- если сменился. Запись в такте
    // line_stb -- первое событие НОВОЙ строки: снимок этой строки взял порт B и
    // палитру до неё.
    if ((is_pal | pb_evt) && (line_stb ? rast_ok : cur_ok)) begin
        if (!line_stb && n == 5'd16)
            ovf <= (&ovf) ? ovf : ovf + 8'd1;       // семнадцатое -- сбой растра
        else begin
            ev_we <= 1'b1;
            ev_wa <= {line_stb ? line_no : cur, line_stb ? 4'd0 : n[3:0]};
            ev_wd <= {is_pal & in_pic & ~line_stb, is_pal ? 1'b0 : 1'b1,
                      is_pal ? pal_pos : pos, is_pal ? din : pb_new};
            n     <= line_stb ? 5'd1 : n + 5'd1;
        end
    end
    if (reset) begin cur_ok <= 1'b0; prev_ok <= 1'b0; sq <= 4'd0; ovf <= 8'd0; end
end

// Запись в журнал: восемь байт за восемь тактов; OUT короче 12 тактов машины
// не бывает, так что следующая запись в порт ничего не застанет.
wire [7:0] lg_hdr = {cur_ok, rast_ok, fpar_cur, 4'b0000, cur[8]};
always @(posedge clk) begin
    lg_we <= 1'b0;
    if (line_stb && line_no == 9'd0) lg_frames <= lg_frames + 8'd1;
    if (rd_stb) begin
        rd_pend <= 1'b1; rdp_kind <= rd_kind; rdp_a <= rd_a; rdp_b <= rd_b;
    end
    if (lg_on) begin
        lg_we <= 1'b1;
        lg_wa <= {lg_wp, lg_b};
        lg_wd <= lg_e[8*lg_b +: 8];
        lg_b  <= lg_b + 3'd1;
        if (lg_b == 3'd7) begin lg_on <= 1'b0; lg_wp <= lg_wp + 7'd1; end
    end
    else if ((is_pal | is_pb | is_ctl) && !lg_hold) begin
        lg_on  <= 1'b1;
        lg_b   <= 3'd0;
        lg_seq <= lg_seq + 8'd1;
        lg_e   <= {lg_seq, port, lg_frames, lg_hdr, cur[7:0], pos,
                   is_pal & in_pic, is_ctl, is_pb, pb[4:0],
                   din};
    end
    else if (rd_pend && !lg_hold && !rd_stb) begin
        rd_pend <= 1'b0;
        lg_on  <= 1'b1;
        lg_b   <= 3'd0;
        lg_seq <= lg_seq + 8'd1;
        lg_e   <= {lg_seq, 6'b111100, rdp_kind, lg_frames, lg_hdr, cur[7:0], pos,
                   rdp_b, rdp_a};
    end
end

endmodule

`default_nettype wire
